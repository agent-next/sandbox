#!/usr/bin/env bash
# judge/setup.sh — install the pinned judge toolchain and base model.
#
# Idempotent. Two things are installed, both sha256-checked:
#
# 1. $HOME/.venvs/gpu-lora-finetune/ — torch 2.14.0+cpu, transformers 5.15.1,
#    peft 0.21.1, safetensors 0.8.0 and the full transitive closure, from
#    judge/requirements-cpu.lock through pip's --require-hashes mode
#    (regenerate the lock with judge/genlock.py).
# 2. $HOME/models/qwen3-0.6b/ — the pinned base model Qwen/Qwen3-0.6B
#    (1.5 GB), every file sha256-checked against judge/pins.txt.
#
# Nothing is `latest`; every pin predates 2026-09-30 (standard: no release
# published in the two weeks before the demo was built). Exit codes: 0 ok,
# 1 install/verification failure, 2 unsupported platform or no network.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
VENV="$HOME/.venvs/gpu-lora-finetune"
LOCK="$SCRIPT_DIR/requirements-cpu.lock"
MODEL_DIR="$HOME/models/qwen3-0.6b"
PINS="$SCRIPT_DIR/pins.txt"
VERSIONS="$SCRIPT_DIR/VERSIONS.txt"

log() { echo "[setup] $*"; }
die() { echo "[setup] ERROR: $*" >&2; exit 1; }

[[ $# -eq 0 ]] || die "takes no arguments (nothing to configure)"

# --- platform guard: x86-64 Linux, CPython 3.10-3.13 (what the lock covers)
case "$(uname -s)-$(uname -m)" in
    Linux-x86_64) ;;
    *) die "unsupported platform $(uname -s)-$(uname -m): the lock pins \
x86-64 Linux wheels (cp310-cp313) only" ;;
esac
PYV="$(python3 -c 'import sys;print(f"{sys.version_info[0]}.{sys.version_info[1]}")')"
case "$PYV" in
    3.10|3.11|3.12|3.13) ;;
    *) die "unsupported CPython $PYV: the lock pins 3.10-3.13 wheels only" ;;
esac

# --- 1. the judge venv ------------------------------------------------------
# requirements.txt is the standard-required pointer; it must match the lock.
grep -q "^## generated by judge/genlock.py" "$LOCK" 2>/dev/null \
    || die "requirements-cpu.lock missing or malformed — run judge/genlock.py"

venv_ok() {
    [[ -x "$VENV/bin/python" ]] || return 1
    "$VENV/bin/python" - <<'PY' >/dev/null 2>&1
import importlib.metadata as im
import sys
want = {
    "torch": "2.14.0+cpu", "transformers": "5.15.1", "peft": "0.21.1",
    "safetensors": "0.8.0", "tokenizers": "0.22.2", "numpy": "2.4.3",
    "huggingface-hub": "1.33.0",
}
for name, ver in want.items():
    try:
        got = im.version(name)
    except im.PackageNotFoundError:
        sys.exit(1)
    if got != ver:
        sys.exit(1)
sys.exit(0)
PY
}

if venv_ok; then
    log "judge venv already provides the pinned versions ($VENV)"
else
    log "creating venv and installing the pinned lock (torch 2.14.0+cpu, \
transformers 5.15.1, peft 0.21.1 ...) — ~200 MB of wheels"
    [[ -d "$VENV" ]] && rm -rf "$VENV"
    python3 -m venv "$VENV"
    # venv pip is unpinned on purpose: it only ever installs the lock below.
    if ! "$VENV/bin/pip" install --quiet --require-hashes \
            --no-cache-dir -r "$LOCK"; then
        die "pip --require-hashes install from requirements-cpu.lock failed \
(hash mismatch or download failure — never retry with hashing off)"
    fi
    venv_ok || die "venv does not provide the pinned versions after install"
fi

# --- 2. the pinned base model ----------------------------------------------
# pins.txt rows: <repo> <file> <bytes> <sha256>
model_ok() {
    [[ -f "$MODEL_DIR/.complete" ]] || return 1
    while read -r repo fname bytes sha; do
        [[ "$repo" == \#* || -z "$repo" ]] && continue
        p="$MODEL_DIR/$fname"
        [[ -f "$p" ]] || return 1
        [[ "$(stat -c%s "$p")" == "$bytes" ]] || return 1
    done < "$PINS"
    return 0
}

if model_ok; then
    log "pinned base model already installed ($MODEL_DIR)"
else
    log "downloading Qwen/Qwen3-0.6B (~1.5 GB) with sha256 verification"
    mkdir -p "$MODEL_DIR"
    rm -f "$MODEL_DIR/.complete"
    while read -r repo fname bytes sha; do
        [[ "$repo" == \#* || -z "$repo" ]] && continue
        p="$MODEL_DIR/$fname"
        url="https://huggingface.co/${repo%/*}/${repo#*/}/resolve/main/$fname"
        for attempt in 1 2 3; do
            if curl -fsSL --retry 2 -o "$p.part" "$url"; then break; fi
            log "download of $fname failed (attempt $attempt); retrying"
            sleep $((attempt * 3))
        done
        [[ -f "$p.part" ]] || die "could not download $fname from $url"
        got="$(sha256sum "$p.part" | cut -d' ' -f1)"
        [[ "$got" == "$sha" ]] || die "sha256 mismatch for $fname: expected \
$sha, got $got — the pinned Qwen3-0.6B revision is gone or corrupted"
        [[ "$(stat -c%s "$p.part")" == "$bytes" ]] || die "size mismatch for \
$fname: expected $bytes bytes"
        mv "$p.part" "$p"
        log "  $fname ok ($bytes bytes)"
    done < "$PINS"
    : > "$MODEL_DIR/.complete"
fi

# --- 3. smoke test + VERSIONS.txt ------------------------------------------
"$VENV/bin/python" - <<'PY'
import torch, transformers, peft, safetensors, numpy
assert torch.__version__ == "2.14.0+cpu", torch.__version__
assert transformers.__version__ == "5.15.1", transformers.__version__
assert peft.__version__ == "0.21.1", peft.__version__
assert safetensors.__version__ == "0.8.0", safetensors.__version__
x = torch.arange(4).float()
assert float((x * x).sum()) == 14.0
print("[setup] venv smoke test ok: torch", torch.__version__)
PY

{
    echo "# What judge/setup.sh actually installed — recorded by the tools'"
    echo "# own --version output, not by hand. Regenerate with:"
    echo "#   bash judge/setup.sh && bash judge/versions.sh > judge/VERSIONS.txt"
    echo "#"
    bash "$SCRIPT_DIR/versions.sh"
} > "$VERSIONS"

log "done: venv $VENV"
log "      model $MODEL_DIR (sha256-pinned by judge/pins.txt)"
