#!/usr/bin/env python3
"""Video frames for the pr-review-agent demo (1920x1080, one card per step).

Usage: make_frames.py <judge_runs_dir> <frames_dir>

The demo has no time-dependent physics, so per DEMO-STANDARD.md the video is
a step-through of the agent loop's figures with captions.  Every number on a
card comes from a verdict JSON written by a real judge run in make_media.sh;
nothing is hand-drawn or invented.  Frames are deterministic (no dates, no
paths) so a regenerate is byte-identical.
"""

from __future__ import annotations

import importlib.util
import json
import os
import sys

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

HERE = os.path.dirname(os.path.abspath(__file__))


def _import_figures():
    spec = importlib.util.spec_from_file_location(
        "make_figures", os.path.join(HERE, "make_figures.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


F = _import_figures()  # shared palette, rcParams and panel functions

KINDS = ["off-by-one (PR 1)", "sql-injection (PR 2)",
         "none-deref (PR 3)", "race (PR 4)"]

GATE_BLURB = [
    ("G1 shape", "the artifact is exactly 6 x (review.json + one test)"),
    ("G2 coverage", "all 4 planted defects matched at |Δline| ≤ 2, right kind, ≥ major"),
    ("G3 clean PRs", "zero major findings on the 2 clean PRs"),
    ("G4 failing test", "each test FAILS on the PR as given (pytest exit 1)"),
    ("G5 passing test", "each test PASSES on the fixed tree (pytest exit 0)"),
    ("G6 isolation", "the artifact never touched the judge or the answer key"),
]


def card_title(fig) -> None:
    fig.text(0.06, 0.72, "pr-review-agent", fontsize=64, color=F.INK,
             fontweight="bold")
    fig.text(0.06, 0.56,
             "An agent reviews 6 pull requests; a judge it cannot fool "
             "grades the review.", fontsize=26, color=F.INK2)
    fig.text(0.06, 0.46, "4 PRs carry one planted defect each — 2 are clean. "
             "A finding counts only if the reviewer's own test\nfails on the "
             "buggy PR and passes on the fix.", fontsize=22, color=F.INK2)
    fig.text(0.06, 0.10, "agent-next sandbox cookbook · regenerated by "
             "media/make_media.sh", fontsize=16, color=F.MUTED)


def card_fixture(fig) -> None:
    fig.text(0.06, 0.84, "The fixture: 6 PRs against one pinned tree",
             fontsize=34, color=F.INK, fontweight="bold")
    for i, kind in enumerate(KINDS):
        y = 0.68 - i * 0.11
        fig.patches.append(matplotlib.patches.FancyBboxPatch(
            (0.06, y), 0.42, 0.075,
            boxstyle="round,pad=0.008,rounding_size=0.015",
            transform=fig.transFigure, facecolor=F.GOOD_TINT,
            edgecolor=F.SURFACE, linewidth=2))
        fig.text(0.09, y + 0.037, kind + " — one planted defect",
                 fontsize=21, color=F.INK)
    for i, what in enumerate(["PR 5 — behaviour-preserving refactor",
                              "PR 6 — new function + its test"]):
        y = 0.68 - (4 + i) * 0.11
        fig.patches.append(matplotlib.patches.FancyBboxPatch(
            (0.06, y), 0.42, 0.075,
            boxstyle="round,pad=0.008,rounding_size=0.015",
            transform=fig.transFigure, facecolor="#eef4fc",
            edgecolor=F.SURFACE, linewidth=2))
        fig.text(0.09, y + 0.037, what + " — clean", fontsize=21,
                 color=F.INK)
    fig.text(0.55, 0.62, "\"any diff is a defect\"\nis not a usable\nheuristic",
             fontsize=26, color=F.INK2)
    fig.text(0.06, 0.10, "judge/fixture/make_fixture.py regenerates and "
             "re-checks the 6 diffs on every setup", fontsize=16,
             color=F.MUTED)


def card_judge(fig) -> None:
    fig.text(0.06, 0.88, "The judge: six numeric gates", fontsize=34,
             color=F.INK, fontweight="bold")
    for i, (gate, blurb) in enumerate(GATE_BLURB):
        y = 0.76 - i * 0.105
        fig.text(0.08, y, gate, fontsize=23, color=F.INK,
                 fontweight="bold")
        fig.text(0.26, y, blurb, fontsize=20, color=F.INK2)
    fig.text(0.06, 0.10, "exit 0 only if all six pass — the verdict JSON "
             "carries every number", fontsize=16, color=F.MUTED)


def card_iteration(fig, upto: int, verdicts: list) -> None:
    caught = [v["gates"]["g2_coverage"]["caught"] for v in verdicts[:upto]]
    fps = [v["gates"]["g3_clean_prs"]["major_findings_on_clean_prs"]
           for v in verdicts[:upto]]
    gate = verdicts[upto - 1]["failed_gate"]
    fig.text(0.06, 0.88, f"Iteration {upto} of 4 — "
             f"{'PASS' if gate is None else 'fails ' + F.GATE_NAMES[gate]}",
             fontsize=34, color=F.INK, fontweight="bold")
    fig.text(0.06, 0.76, f"defects caught: {caught[-1]} / 4      "
             f"majors on clean PRs: {fps[-1]}      seed 42",
             fontsize=24, color=F.INK2)
    ax = fig.add_axes([0.14, 0.30, 0.72, 0.36])
    ax.set_xlim(0.5, 4.5)
    ax.set_ylim(-0.4, 5.6)
    ax.set_yticks(range(0, 5))
    ax.set_xticks(range(1, 5))
    ax.set_xticklabels([f"iter {i}" for i in range(1, 5)], color=F.INK2)
    ax.axhline(4, color=F.GREEN, lw=1.8)
    ax.text(4.06, 4, "pass rule 4/4", color="#006300", fontsize=15,
            va="center")
    ax.plot(range(1, upto + 1), caught, color=F.BLUE, lw=2.5, marker="o",
            markersize=12, markeredgecolor=F.SURFACE, markeredgewidth=1.5)
    ax.plot(range(1, upto + 1), fps, color=F.ORANGE, lw=2.5, marker="o",
            markersize=12, markeredgecolor=F.SURFACE, markeredgewidth=1.5)
    if upto == 4:
        ax.annotate("all six gates pass", (4, 4), textcoords="offset points",
                    xytext=(-10, 22), ha="right", color="#006300",
                    fontsize=20)
    ax.set_ylabel("count", color=F.INK2)
    fig.text(0.14, 0.22, "blue: defects caught (G2)    orange: majors on "
             "clean PRs (G3)", fontsize=18, color=F.INK2)


def card_verdict(fig, good) -> None:
    fig.text(0.06, 0.88, "The verdict", fontsize=34, color=F.INK,
             fontweight="bold")
    fig.text(0.06, 0.78, "judge/grade.sh examples/good/review --seed 42 "
             " →  exit 0", fontsize=22, color=F.INK2)
    rows = [
        ("G2", f"{good['gates']['g2_coverage']['caught']} / "
               f"{good['gates']['g2_coverage']['planted']} defects caught"),
        ("G3", f"{good['gates']['g3_clean_prs']['major_findings_on_clean_prs']}"
               " majors on the clean PRs"),
        ("G4", "4 / 4 reviewer tests fail the buggy PR"),
        ("G5", "4 / 4 reviewer tests pass the fix"),
    ]
    for i, (gate, text) in enumerate(rows):
        y = 0.64 - i * 0.10
        fig.text(0.10, y, f"✓ {gate}", fontsize=24, color="#006300",
                 fontweight="bold")
        fig.text(0.22, y, text, fontsize=24, color=F.INK)
    fig.text(0.06, 0.16, "self-test kill rate 10/10 · two --seed 42 grades "
             "byte-identical but for timing", fontsize=18, color=F.INK2)
    fig.text(0.06, 0.10, "agent-next sandbox cookbook · regenerated by "
             "media/make_media.sh", fontsize=16, color=F.MUTED)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: make_frames.py <judge_runs_dir> <frames_dir>",
              file=sys.stderr)
        return 2
    runs_dir, frames_dir = sys.argv[1], sys.argv[2]
    replay = os.path.join(runs_dir, "replay")
    os.makedirs(frames_dir, exist_ok=True)

    def verdict(name):
        with open(os.path.join(replay, "verdicts", name),
                  encoding="utf-8") as f:
            return json.load(f)

    verdicts = [verdict(f"it{i}.json") for i in range(1, 5)]
    good = verdicts[3]
    with open(os.path.join(replay, "mutants", "wrong-line-race.json"),
              encoding="utf-8") as f:
        wl = json.load(f)
    with open(os.path.join(replay, "mutants", "wrong-line-race", "pr4",
                           "review.json"), encoding="utf-8") as f:
        wl_reported = json.load(f)["findings"][0]["line"]
    wl_missed = [d for d in wl["gates"]["g2_coverage"]["missed"]
                 if d["kind"] == "race"][0]
    runs = {
        "good": good,
        "wrong-line-race": wl,
        "wrong-kind-none-deref":
            json.load(open(os.path.join(replay, "mutants",
                                        "wrong-kind-none-deref.json"),
                           encoding="utf-8")),
        "src": {
            "wrong-line-race": os.path.join(
                replay, "mutants", "wrong-line-race", "pr4", "review.json"),
            "wrong-kind-none-deref": os.path.join(
                replay, "mutants", "wrong-kind-none-deref", "pr3",
                "review.json"),
        },
    }

    cards = []

    def new_card(draw):
        fig = plt.figure(figsize=(19.2, 10.8), dpi=100)
        draw(fig)
        cards.append(fig)

    new_card(card_title)
    new_card(card_fixture)
    new_card(card_judge)
    for upto in range(1, 5):
        new_card(lambda fig, u=upto: card_iteration(fig, u, verdicts))

    def _loc(fig):
        ax = fig.add_axes([0.07, 0.14, 0.86, 0.66])
        F.panel_localization(ax, runs)
        fig.text(0.07, 0.90, "Gate G2 — localization", fontsize=34,
                 color=F.INK, fontweight="bold")

    def _disc(fig):
        ax = fig.add_axes([0.30, 0.14, 0.42, 0.66])
        F.panel_discrimination(ax, good)
        fig.text(0.07, 0.90, "Gates G4+G5 — the tests discriminate",
                 fontsize=34, color=F.INK, fontweight="bold")

    new_card(_loc)
    new_card(_disc)
    new_card(lambda fig: card_verdict(fig, good))

    for i, fig in enumerate(cards):
        fig.savefig(os.path.join(frames_dir, f"frame_{i:04d}.png"))
        plt.close(fig)
    print(f"  wrote {len(cards)} frames to {frames_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
