#!/usr/bin/env python3
"""Regenerate media/requirements.lock (sha256 pins for the rendering venv).

Usage:  python3 media/genlock.py

Wheel hashes are fetched live from the PyPI JSON API. Only wheels usable
on x86-64 Linux CPython 3.10-3.13 plus pure wheels are listed, so
`pip --require-hashes` stays exact on the supported platforms.

The date rule from the cookbook standard applies: every pin predates
2026-09-30 (nothing published in the two weeks before this demo was
built). numpy 2.5.4 (2026-10-10) and fonttools 4.67.0 (2026-10-06)
postdate the cutoff, so the pins are the newest compatible older
releases.
"""

import json
import urllib.request

CUTOFF = "2026-09-30"          # date rule: no release published after this
CPS = ("cp310", "cp311", "cp312", "cp313")
PYPI = "https://pypi.org/pypi/{}/json"

# name -> version. All verified to predate the cutoff.
PINS = [
    ("matplotlib", "3.11.2"),
    ("numpy", "2.5.3"),
    ("contourpy", "1.4.0"),
    ("cycler", "0.12.1"),
    ("fonttools", "4.66.1"),
    ("kiwisolver", "1.5.1"),
    ("packaging", "26.3"),
    ("pillow", "12.3.0"),
    ("pyparsing", "3.3.3"),
    ("python-dateutil", "2.9.0.post0"),
    ("six", "1.17.0"),
]


def usable(filename):
    """x86-64 Linux wheels (cp310-cp313 or py3) and pure wheels only."""
    if "none-any" in filename:
        return True
    if "x86_64" not in filename or "aarch64" in filename:
        return False
    if "py3-none" in filename:
        return True
    return any(cp in filename for cp in CPS) and "cp313t" not in filename


def check_date(name, version, files):
    if not files:
        raise SystemExit(f"{name} {version}: no usable wheel found")
    dates = sorted({f["upload_time"][:10] for f in files})
    if dates[-1] > CUTOFF:
        raise SystemExit(
            f"{name} {version}: published {dates[-1]}, after the {CUTOFF} date rule")


def main():
    lines = [
        "## generated by media/genlock.py -- pip install --require-hashes",
        "## wheels: x86-64 Linux, CPython 3.10-3.13 (see genlock.py)",
        "## date rule: every pin predates 2026-09-30",
    ]
    for name, version in PINS:
        data = json.load(urllib.request.urlopen(PYPI.format(f"{name}/{version}")))
        files = [f for f in data["urls"] if usable(f["filename"])]
        check_date(name, version, files)
        lines.append(f"{name}=={version} \\")
        for f in files:
            lines.append(f"    --hash=sha256:{f['digests']['sha256']} \\")
        lines[-1] = lines[-1].rstrip(" \\")
        print(f"{name}=={version}: {len(files)} wheel(s), "
              f"latest upload {sorted({f['upload_time'][:10] for f in files})[-1]}")
    out = __file__.replace("genlock.py", "requirements.lock")
    with open(out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
