#!/usr/bin/env python3
"""G6 perf driver for the fpga-agent-loop judge (SPEC G6; not a gate).

Runs the fixed benchmark (tests/perf/bench.hex, generated by gen_bench.py:
bubble sort of 64 words + mod-2^32 checksum) on the Verilator DUT under
0-latency memory, runs it on the ISS (iss.py) as the oracle, compares the
checksum word (0x040) between the two resulting memory images, and reports
CPI = DUT cycles / ISS retired instructions.

Prints exactly one JSON object to stdout:
  {"pass": bool, "detail": str, "cpi": float|null, "cycles": int|null,
   "insns": int|null, "checksum": "0x........"|null, "checksum_ok": bool}
pass = DUT reached tohost==1 AND ISS reached tohost==1 AND checksums agree.
G6 is informational: grade.sh records it but it does not gate the verdict.

Usage: g6check.py --sim SIM [--bench HEX] [--max-cycles N]
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import iss
import memh

CHECKSUM_WORD = 0x040 // 4
MAX_STEPS = 4_000_000


def main(argv):
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--sim", required=True)
    p.add_argument("--bench", default=os.path.join(
        os.path.dirname(os.path.abspath(__file__)), "tests", "perf",
        "bench.hex"))
    p.add_argument("--max-cycles", type=int, default=MAX_STEPS)
    a = p.parse_args(argv[1:])

    out = {"pass": False, "detail": "", "cpi": None, "cycles": None,
           "insns": None, "checksum": None, "checksum_ok": False}

    words = memh.load_memh(a.bench)

    # ---- oracle ----------------------------------------------------------
    m = iss.RV32ISS(words)
    status = m.run(MAX_STEPS)
    if status != "PASS":
        out["detail"] = ("JUDGE ERROR: ISS did not reach tohost==1 "
                         "(status=%s) - benchmark bug" % status)
        print(json.dumps(out))
        return 2
    insns = m.steps
    expected = m.image()[CHECKSUM_WORD]

    # ---- DUT --------------------------------------------------------------
    work = tempfile.mkdtemp(prefix="g6check.")
    hexf = os.path.join(work, "bench.hex")
    dumpf = os.path.join(work, "bench.dut.hex")
    memh.dump_memh(words, hexf)
    r = subprocess.run([a.sim, "--hex", hexf, "--max-cycles",
                        str(a.max_cycles), "--dump", dumpf],
                       capture_output=True, text=True)
    line = r.stdout.strip()
    fields = dict(kv.split("=", 1) for kv in line.split()
                  if "=" in kv)
    if not line.startswith("RESULT") or "CYCLES" not in fields:
        out["detail"] = ("sim did not produce a RESULT line: '%s'" % line)
        print(json.dumps(out))
        return 1
    cycles = int(fields["CYCLES"])
    got = memh.load_memh(dumpf)[CHECKSUM_WORD]

    dut_ok = line.startswith("RESULT PASS")
    ck_ok = got == expected
    out["cycles"] = cycles
    out["insns"] = insns
    out["checksum"] = "0x%08x" % got
    out["checksum_ok"] = ck_ok
    out["cpi"] = round(cycles / insns, 4) if insns else None
    out["pass"] = bool(dut_ok and ck_ok)
    out["detail"] = (
        "cpi=%.4f (%d cycles / %d insns); checksum 0x%08x %s ISS%s"
        % (cycles / insns if insns else 0.0, cycles, insns, got,
           "==" if ck_ok else "!=", "" if dut_ok else
           "; DUT result: %s" % line))
    print(json.dumps(out))
    return 0 if out["pass"] else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
