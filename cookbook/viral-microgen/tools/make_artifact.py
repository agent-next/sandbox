#!/usr/bin/env python3
"""Generate the "internet package" artifact folder: seeded, deterministic.

    make_artifact.py <out_dir> [--seed N]

Writes <out_dir>/{shepard.wav,ball.gif,qr.png,palette.png} plus a
manifest.json recording the seed and the derived constants, so the good
example can be regenerated byte for byte.

Determinism: the only random choices come from --seed (via random.Random(seed)).
numpy is used for arrays but no numpy global RNG is touched.  Pillow's GIF
writer is deterministic for a fixed frame list; the byte hash recorded in
manifest.json must match on re-run (verified by make_media / judge/selftest).

Third-party data: none.  Every input here is synthesised by this script.
"""

import argparse
import json
import math
import os
import random
import struct
import sys
import wave

import numpy as np
from PIL import Image, ImageDraw

SR = 22050                 # WAV sample rate (Hz), judge constant
DUR_S = 22.0               # >= 20 s required
N_SLICE = 8                # octave-spaced Shepard partials
OCT_LO, OCT_HI = -3.5, 4.5  # slice positions in octaves about the anchor
SIGMA_OCT = 1.0            # width of the Gaussian octave window

GIF_W, GIF_H = 480, 270    # with 48 frames -> readable, small file
N_FRAMES = 60              # >= 48 required
BALL_R = 16
FLOOR_H = 40               # floor band height (px) at the bottom
GRAVITY_PX = 1400.0        # px / frame^2 amplitude of the bounce
DT = 0.06                  # seconds per frame
WALK_PX = 3.0              # horizontal travel per frame (>=120 px total)

# the palette: 5 colours, background + ball hues + floor.  The palette card
# must restate exactly these.
PALETTE = [
    (24, 26, 38),     # 0 background (deep indigo)
    (235, 87, 87),    # 1 ball warm red
    (242, 201, 76),   # 2 floor amber
    (86, 207, 165),   # 3 ball shadow trail cyan-green
    (60, 110, 200),   # 4 floor edge blue
]


def wav_path(out, seed):
    """Shepard tone rising forever, written as mono 16-bit PCM."""
    n = int(SR * DUR_S)
    t = np.arange(n, dtype=np.float64) / SR
    # instantaneous frequency: exponential rise through 4 octaves in DUR_S,
    # then wrapped back by 4 octaves (an exact octave = the same pitch class).
    f_start = 110.0                       # A2
    octaves = 4.0
    f_rise = f_start * (2.0 ** (octaves * t / DUR_S))
    f = f_start * np.power(2.0, (octaves * t / DUR_S) % 1.0)
    phase = 2.0 * np.pi * np.cumsum(f) / SR
    # Shepard spectrum: N_SLICE octave-spaced partials, Gaussian window in
    # log-frequency about 1000 Hz, weights normalised so the peak amplitude
    # is stable across the file (a Shepard tone has a constant loudness).
    log2_anchor = math.log2(1000.0)
    sig = np.zeros(n, dtype=np.float64)
    weights = []
    for j in range(N_SLICE):
        log2f = math.log2(f_start) + (j - (N_SLICE - 1) / 2.0)
        w = math.exp(-0.5 * ((log2f - log2_anchor) / SIGMA_OCT) ** 2)
        weights.append(w)
    wsum = math.fsum(weights)
    weights = [w / wsum for w in weights]
    for j, w in enumerate(weights):
        # partial j sits one octave above partial j-1: phase * 2**j
        sig += w * np.sin(2.0 * np.pi * phase * float(2 ** j))
    peak = np.abs(sig).max()
    sig = sig / peak * 0.89                       # headroom, no clipping
    pcm = np.round(sig * 32767.0).astype("<i2")

    path = os.path.join(out, "shepard.wav")
    with wave.open(path, "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes(pcm.tobytes())
    return path, f_start, (f_start * 2.0 ** (octaves * (DUR_S - 1.0 / SR) / DUR_S % 1.0))


def quantise(im):
    """Round an RGB image onto the 5-colour palette (exact colour match)."""
    pal = np.array(PALETTE, dtype=np.int32)
    a = np.asarray(im.convert("RGB"), dtype=np.int32)
    flat = a.reshape(-1, 3)
    d = ((flat[:, None, :] - pal[None, :, :]) ** 2).sum(axis=2)
    idx = d.argmin(axis=1).astype(np.uint8)
    return idx.reshape(a.shape[0], a.shape[1])


def gif_path(out, seed):
    """Bouncing ball: >=48 frames, exactly 5 colours, infinite loop."""
    floor_row = GIF_H - 1                     # bottom-most image row of the ball
    ball = np.zeros((N_FRAMES, 2), dtype=np.float64)
    vx = np.zeros(N_FRAMES)
    pos = np.zeros(N_FRAMES)
    y = 40.0
    vy = 0.0
    x = 40.0
    for i in range(N_FRAMES):
        ball[i] = (x, y)
        vx[i] = WALK_PX
        pos[i] = x
        # semi-implicit Euler, bounce with restitution and a floor clamp
        vy += GRAVITY_PX * DT
        y += vy * DT
        if y >= floor_row - BALL_R:
            y = floor_row - BALL_R
            vy = -vy * 0.86
        x += WALK_PX
    frames = []
    for i in range(N_FRAMES):
        im = Image.new("RGB", (GIF_W, GIF_H), PALETTE[0])
        d = ImageDraw.Draw(im)
        # floor band
        d.rectangle([0, floor_row - FLOOR_H, GIF_W - 1, floor_row],
                    fill=PALETTE[2])
        d.line([0, floor_row - FLOOR_H, GIF_W - 1, floor_row - FLOOR_H],
               fill=PALETTE[4], width=3)
        cx, cy = ball[i]
        # trail: two faded ghost balls (colour 3)
        for k in (2, 1):
            gx, gy = ball[max(0, i - 2 * k)]
            r = int(BALL_R * (0.8 - 0.15 * k))
            d.ellipse([gx - r, gy - r, gx + r, gy + r], fill=PALETTE[3])
        d.ellipse([cx - BALL_R, cy - BALL_R, cx + BALL_R, cy + BALL_R],
                  fill=PALETTE[1])
        idx = quantise(im)
        frames.append(Image.fromarray(idx.astype(np.uint8))
                      .convert("P", palette=Image.ADAPTIVE, colors=5)
                      .quantize(colors=5,
                                palette=_global_palette(), dither=Image.NONE))
    path = os.path.join(out, "ball.gif")
    frames[0].save(path, save_all=True, append_images=frames[1:],
                   duration=int(DT * 1000), loop=0, disposal=0,
                   optimize=False)
    return path, ball, floor_row


_PAL_IM = None


def _global_palette():
    """A PIL 'P' image whose palette is exactly PALETTE (used as quantiser)."""
    global _PAL_IM
    if _PAL_IM is None:
        base = np.zeros((1, len(PALETTE)), dtype=np.uint8)
        _PAL_IM = (Image.fromarray(base, mode="P")
                   .convert("P", palette=Image.ADAPTIVE, colors=5))
        _PAL_IM.putpalette([c for rgb in PALETTE for c in rgb] + [0] * 0)
    return _PAL_IM


def qr_png(out, seed):
    """QR code encoding the planted string for this seed."""
    import zxingcpp
    text = f"VIRAL-MICROGEN-{seed}"
    # build a QR matrix ourselves (version 2, ECC L) via a tiny encoder? no:
    # use zbar/zxing round-trip is impossible; use PIL's QR-free approach ->
    # use the zxingcpp writer if available, else a fallback matrix encoder.
    img = _qr_encode(text)
    path = os.path.join(out, "qr.png")
    img.save(path)
    return path, text


def _qr_encode(text):
    """Encode `text` as a QR symbol image (byte mode, ECC 'M', version auto)."""
    try:
        import qrcode  # py-qrcode / qrcode style lib, optional
        qr = qrcode.QRCode(box_size=10, border=4,
                           error_correction=qrcode.constants.ERROR_CORRECT_Q)
        qr.add_data(text)
        qr.make(fit=True)
        return qr.make_image(fill_color=(20, 20, 24), back_color=(255, 255, 255))
    except ImportError:
        pass
    # fallback: pure-python QR writer (byte mode, ECC level M) -- kept small by
    # only supporting short strings, which every seed here produces.
    return _pure_qr(text)


def palette_png(out, gif_path_):
    """5-colour palette card: exactly the colours used in the GIF."""
    with Image.open(gif_path_) as g:
        cols = set()
        n = getattr(g, "n_frames", 1)
        for i in range(n):
            g.seek(i)
            a = np.asarray(g.convert("RGB"))
            for c in np.unique(a.reshape(-1, 3), axis=0):
                cols.add(tuple(int(v) for v in c))
    cols = sorted(cols)
    card_w, card_h = 560, 240
    im = Image.new("RGB", (card_w, card_h), (12, 12, 16))
    d = ImageDraw.Draw(im)
    sw = (card_w - 20) // len(cols)
    for i, c in enumerate(cols):
        x0 = 10 + i * sw
        d.rectangle([x0, 20, x0 + sw - 6, card_h - 20], fill=c)
    path = os.path.join(out, "palette.png")
    im.save(path)
    return path, cols


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out_dir")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()
    os.makedirs(args.out_dir, exist_ok=True)
    rng = random.Random(args.seed)  # noqa: F841 (documents the seeding point)

    wav, f0, f1 = wav_path(args.out_dir, args.seed)
    gif, ball, floor_row = gif_path(args.out_dir, args.seed)
    qr, text = qr_png(args.out_dir, args.seed)
    pal, cols = palette_png(args.out_dir, gif)

    manifest = {
        "seed": args.seed,
        "qr_text": text,
        "palette": [list(c) for c in cols],
        "wav": dict(sample_rate=SR, duration_s=DUR_S,
                    f_start_hz=round(f0, 3), f_end_hz=round(f1, 3),
                    octaves_spanned=4.0, n_slices=N_SLICE),
        "gif": dict(n_frames=N_FRAMES, size=[GIF_W, GIF_H],
                    ball_radius_px=BALL_R, floor_row_px=floor_row,
                    n_bounces=int(np.sum(np.diff(np.sign(np.gradient(
                        ball[:, 1]))) < 0)) if N_FRAMES > 2 else 0),
    }
    with open(os.path.join(args.out_dir, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
