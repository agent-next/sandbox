"""Headless 3D renders for the aicad-cadam media (pyrender on OSMesa).

Every mesh rendered here is loaded from a real file of this run — the
shipped examples/good/<case>/part.stl, the judge-built OCCT reference
solid (rebuilt from the spec table by judge/cases.py exactly as the
judge's gate 7 does), or a mutant STL regenerated by judge/mutants.py —
and every XOR solid is computed with the same manifold3d 3.0.1 code path
judge/check_gates.py uses.  No mesh is synthesised.

pyrender 0.1.45 + PyOpenGL 3.1.0 need two documented shims on Debian
bookworm's Mesa 22.3.6 (see osmesa_shim()); make_media.sh runs this with
PYOPENGL_PLATFORM=osmesa.  Requires the judge's pinned wheels (trimesh,
manifold3d, cadquery-ocp) — the same versions judge/requirements.txt
installs.
"""

