def _hex(h):
    return [int(h[i:i + 2], 16) / 255.0 for i in (1, 3, 5)] + [1.0]


def osmesa_shim():
    """Make pyrender's OSMesa platform work on Debian bookworm.

    Two upstream gaps, both documented in media/REVIEW.md:
      1. PyOpenGL 3.1.0's opaque OSMesaContext pointer is unhashable, so
         PyOpenGL's per-context extension cache raises TypeError: unhashable
         type the moment pyrender binds a core-profile function.
      2. pyrender 0.1.45 passes OSMesaCreateContextAttribs the context
         version under the slot ids Mesa uses for
         OSMESA_PROFILE/OSMESA_CONTEXT_MAJOR_VERSION (0x33/0x34/0x35);
         bookworm's Mesa 22.3.6 rejects those and accepts 0x36/0x37 as
         CONTEXT_MAJOR/MINOR_VERSION_NR (verified by probing; see
         REVIEW.md), so the attrib list is rewritten for this Mesa.
    """
    from OpenGL.raw.osmesa._types import OSMesaContext
    OSMesaContext.__hash__ = lambda self: id(self)

    import pyrender.platforms.osmesa as pr_osa
    from OpenGL import arrays
    from OpenGL.platform import PLATFORM

    def init_context(self):
        f = PLATFORM.OSMesa.OSMesaCreateContextAttribs
        f.restype = ctypes.c_void_p
        f.argtypes = [ctypes.POINTER(ctypes.c_int), ctypes.c_void_p]
        attrs = arrays.GLintArray.asArray(
            [0x22, 6408,        # OSMESA_FORMAT, OSMESA_RGBA
             0x30, 24,          # OSMESA_DEPTH_BITS, 24
             0x36, 3, 0x37, 3,  # CONTEXT_MAJOR/MINOR_VERSION_NR (Mesa 22.x)
             0])
        self._context = f(attrs, None)
        self._buffer = arrays.GLubyteArray.zeros(
            (self.viewport_height, self.viewport_width, 4))

    pr_osa.OSMesaPlatform.init_context = init_context


def lookat(eye, target):
    """Camera pose looking from eye at target (pyrender cameras look -z)."""
    eye, target = np.asarray(eye, float), np.asarray(target, float)
    z = eye - target
    z = z / np.linalg.norm(z)
    x = np.cross([0.0, 1.0, 0.0], z)
    x = x / np.linalg.norm(x)
    y = np.cross(z, x)
    t = np.eye(4)
    t[:3, 0], t[:3, 1], t[:3, 2], t[:3, 3] = x, y, z, eye
    return t


def orbit_pose(center, r, azim_deg, elev_deg=25.0):
    """Camera pose on a sphere of radius r around center (degrees)."""
    a, e = np.radians(azim_deg), np.radians(elev_deg)
    eye = center + r * np.array([np.cos(e) * np.cos(a),
                                 np.cos(e) * np.sin(a),
                                 np.sin(e)])
    return lookat(eye, center)


class Turntable:
    """One renderer reused across frames: scenes are swapped per shot.

    The renderer holds the GL context; rebuilding it per frame leaks
    buffers under OSMesa, so a single OffscreenRenderer is created and
    every shot() call renders a freshly built scene.
    """

    def __init__(self, w, h):
        import pyrender
        self.w, self.h = w, h
        self.r = pyrender.OffscreenRenderer(w, h)

    def close(self):
        self.r.delete()

    def shot(self, scene):
        color, _ = self.r.render(scene)
        return color


def build_scene(meshes, camera_pose, yfov=np.pi / 3.0,
                bg=(0.055, 0.055, 0.051, 1.0), light_amb=0.28,
                lights=(([0.5, 0.5, 1.0], 2.4), ([-0.7, 0.2, 0.5], 1.1),
                         ([0.2, -0.8, 0.3], 0.7))):
    """Scene with the given (mesh, color, pose, style) entries.

    meshes: list of (trimesh.Trimesh, hexcolor, pose4x4, style) where
    style is 'solid' | 'wire' (line-width-scaled wireframe) | 'both'.
    """
    import pyrender

    scene = pyrender.Scene(ambient_light=[light_amb] * 3, bg_color=bg)
    for tm, hexc, pose, style in meshes:
        mat = pyrender.MetallicRoughnessMaterial(
            baseColorFactor=_hex(hexc), metallicFactor=0.05,
            roughnessFactor=0.55)
        m = pyrender.Mesh.from_trimesh(tm, material=mat, smooth=False)
        node = scene.add(m, pose=pose)
        if style in ("wire", "both"):
            w = pyrender.Mesh.from_trimesh(
                tm, material=pyrender.MetallicRoughnessMaterial(
                    baseColorFactor=_hex(WHITE), metallic_factor=0.0,
                    roughness_factor=1.0), smooth=False,
                wireframe=True, wireframe_width=1.6)
            scene.add(w, pose=pose, parent_node=node)
    scene.add(pyrender.PerspectiveCamera(yfov=yfov), pose=camera_pose)
    for d, i in lights:
        lp = np.eye(4)
        lp[:3, :3] = trimesh.geometry.align_vectors(
            [0, 0, 1], d)[:3, :3]
        lp[2, 3] = 10.0
        scene.add(pyrender.DirectionalLight(intensity=i), pose=lp)
    return scene


