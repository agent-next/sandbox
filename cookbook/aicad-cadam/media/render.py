def load_case_meshes(demo_dir, case):
    """(shipped STL, judge-built OCCT reference mesh) for a good case."""
    sys.path.insert(0, os.path.join(demo_dir, "judge"))
    from cases import reference_solid
    from check_gates import occt_mesh_arrays  # noqa: E402  judge's own code

    stl = trimesh.load(os.path.join(demo_dir, "examples/good", case,
                                    "part.stl"))
    ref = reference_solid(case)  # judge's oracle solid, spec table only
    rv, rf = occt_mesh_arrays(ref)
    ref_tm = trimesh.Trimesh(vertices=rv, faces=rf)
    return stl, ref_tm


def xor_mesh(a_tm, b_tm):
    """Symmetric-difference solid via the judge's manifold3d composition:
    (A-B) u (B-A) — same code path as check_gates.xor_volume."""
    from manifold3d import Manifold, Mesh, OpType

    def to_m(tm):
        return Manifold(Mesh(
            vert_properties=np.asarray(tm.vertices, dtype=np.float32),
            tri_verts=np.asarray(tm.faces, dtype=np.uint32)))

    amb = Manifold.batch_boolean([to_m(a_tm), to_m(b_tm)], OpType.Subtract)
    bma = Manifold.batch_boolean([to_m(b_tm), to_m(a_tm)], OpType.Subtract)
    both = Manifold.batch_boolean([amb, bma], OpType.Add)
    mesh = both.to_mesh()
    v = np.asarray(mesh.vert_properties)[:, :3]
    f = np.asarray(mesh.tri_verts)
    return trimesh.Trimesh(vertices=v, faces=f)


def gate_map(verdict_path):
    """{gate_name: entry} from a judge verdict JSON."""
    with open(verdict_path) as f:
        v = json.load(f)
    return {g["gate"]: g for g in v["gates"]}, v


def frame_center(tm):
    return ((tm.bounds[0] + tm.bounds[1]) / 2.0).astype(float)
