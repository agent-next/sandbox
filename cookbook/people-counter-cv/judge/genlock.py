#!/usr/bin/env python3
"""Regenerate judge/requirements.lock (sha256 pins).

Usage:  python3 judge/genlock.py

Wheel hashes are fetched live from the PyPI JSON API. Only wheels usable
on x86-64 Linux CPython 3.10-3.13 plus pure wheels are listed, so
`pip --require-hashes` stays exact on the supported platforms (the judge's
setup.sh refuses to run elsewhere).

The date rule from the cookbook standard applies: every pin predates
2026-09-30 (nothing published in the two weeks before this demo was
built). Where pip would resolve something newer (numpy 2.5.4), the pin
is the newest compatible older release; the judge never upgrades past
the pin because the closure is pinned in full.
"""

import json
import urllib.request

CUTOFF = "2026-09-30"          # date rule: no release published after this
CPS = ("cp310", "cp311", "cp312", "cp313")
PYPI = "https://pypi.org/pypi/{}/json"

# name -> version. numpy 2.5.4 (2026-10-10) postdates the cutoff.
PINS = [
    ("opencv-python-headless", "4.13.0.92"),
    ("numpy", "2.5.3"),
]


def usable(filename):
    """x86-64 Linux wheels (cp310-cp313, py3 or the cp37 stable ABI) and
    pure wheels only."""
    if "none-any" in filename:
        return True
    if "x86_64" not in filename or "aarch64" in filename:
        return False
    if "py3-none" in filename or "cp37-abi3" in filename:
        return True
    return any(cp in filename for cp in CPS) and "cp313t" not in filename


def check_date(name, version, files):
    if not files:
        raise SystemExit(f"{name} {version}: no usable wheel found")
    dates = sorted({f["upload_time"][:10] for f in files})
    if dates[-1] > CUTOFF:
        raise SystemExit(
            f"{name} {version}: published {dates[-1]}, after the {CUTOFF} date rule")


def pypi_hashes(name, version):
    with urllib.request.urlopen(PYPI.format(f"{name}/{version}"), timeout=60) as r:
        data = json.load(r)
    files = [u for u in data["urls"] if usable(u["filename"])]
    check_date(name, version, files)
    return sorted(u["digests"]["sha256"] for u in files)


def main():
    lines = ["## generated by judge/genlock.py -- pip install --require-hashes",
             "## wheels: x86-64 Linux, CPython 3.10-3.13 (see genlock.py)"]
    for name, version in PINS:
        hashes = pypi_hashes(name, version)
        lines.append(f"{name}=={version} \\")
        for h in hashes:
            lines.append(f"    --hash=sha256:{h} \\")
        lines[-1] = lines[-1][:-2]     # drop the trailing backslash
    out = "\n".join(lines) + "\n"
    with open("requirements.lock", "w") as fh:
        fh.write(out)
    print(out)


if __name__ == "__main__":
    main()
