set -euo pipefail

cd "$(dirname "$0")/.."
DEMO_DIR="$(pwd)"
JUDGE_DIR="$DEMO_DIR/judge"
PREFIX="${NANOUSD_RENDER_PREFIX:-$HOME/.nanousd-render}"
PY="$PREFIX/venv/bin/python"
MEDIA_DIR="$DEMO_DIR/media"
BUILD_DIR="$MEDIA_DIR/build"
MASTER_DIR="$MEDIA_DIR/master"
SETUP_LOG="$BUILD_DIR/setup_run.log"

if [ ! -x "$PY" ]; then
    echo "[make_media] ERROR: run judge/setup.sh first (missing $PY)" >&2
    exit 1
fi

export NANOUSD_RENDER_PREFIX="$PREFIX"
export LIBGL_ALWAYS_SOFTWARE=1
export GALLIUM_DRIVER=llvmpipe
export LD_LIBRARY_PATH="$PREFIX/build/nanousd-opengl-renderer:$PREFIX/build/nanousd-opengl-renderer/Release:$PREFIX/build/nanousd/Release:${LD_LIBRARY_PATH:-}"

rm -rf "$BUILD_DIR"; mkdir -p "$BUILD_DIR" "$MASTER_DIR"

# 1. the real setup run this media is built from: its own log and its own
#    measured wall time go to media/build/, so the terminal shot and the
#    "Nx speed" badge both trace to a log THIS script wrote (never to a
#    /tmp file left behind by an earlier session, never to a hard-coded
#    fallback). It runs first because everything below needs the toolchain.
setup_t0=$(date +%s)
bash "$JUDGE_DIR/setup.sh" 2>&1 | tee "$SETUP_LOG" | tail -20
setup_wall_s=$(( $(date +%s) - setup_t0 ))
echo "[make_media] setup.sh wall ${setup_wall_s}s (log: media/build/setup_run.log)"
grep -E '^\[setup\] ' "$SETUP_LOG" > "$MEDIA_DIR/setup_progress.txt" || true

# 2. grade the known-good example: verdict.json carries G4 attrs (rects, k)
"$JUDGE_DIR/grade.sh" "$DEMO_DIR/examples/good/scene.usda" \
    --seed 0 --json "$BUILD_DIR/verdict.json" | tail -3

# 3. scene dump from the pinned nanousd C dumper (out-of-process, exactly
#    the way G2 reads the primes)
"$PREFIX/bin/nanousd_dump" "$PREFIX/build/nanousd/Release/libnanousd.so" \
    "$DEMO_DIR/examples/good/scene.usda" > "$BUILD_DIR/scene_dump.json"

# 4. selftest.json (mutant kill matrix)
"$JUDGE_DIR/selftest.sh" --json "$BUILD_DIR/selftest.json" \
    >"$BUILD_DIR/selftest.log" 2>&1 || {
        cat "$BUILD_DIR/selftest.log" >&2
        exit 1
    }

# 5. figures (result.png + loop.png) from the judge outputs above
"$PY" "$MEDIA_DIR/figures.py"

# 6. media/result.json -- one manifest (agent-next/result@1) carrying the
#    same numbers the figures and the video put on screen
"$PY" "$MEDIA_DIR/write_result.py"

# 7. video (master mp4 ignored, web encode committed)
DEMO_SETUP_WALL_S="$setup_wall_s" "$PY" "$MEDIA_DIR/build_video.py"

# 8. MANIFEST.json: for each committed file -- what it shows, the command
#    that produced it, the source data file, sha256. Lossless masters
#    (media/master/), the build scratch tree (media/build/) and Python
#    bytecode caches are git-ignored and are NOT listed.
"$PY" - "$MEDIA_DIR" <<'PY'
import hashlib, json, os, subprocess, sys

MEDIA = sys.argv[1]

# file -> (what it shows, the command that produced it, the source data file)
# Every entry is generated from a judge output, never hand-edited.
META = {
    "probe_cuts.py": (
        "Development probe: renders only the slot-boundary frames and "
        "measures ffmpeg's real scene-cut score across each cut, so a cut "
        "video_gate.py will not count is found for a few renders instead of "
        "a full re-cut. Not part of the mp4.",
        "hand-written; run by hand while cutting video",
        "media/build/verdict.json, media/build/selftest.json"),
    "result.png": (
        "Hero still: the judge's own 640x480 graded render of "
        "examples/good/scene.usda with the G4 numpy pinhole oracle's "
        "projected rectangles (the pass line) and the per-mesh measured "
        "illuminance k drawn on the real pixels, beside the verdict panel.",
        "judge/grade.sh examples/good/scene.usda --seed 0 "
        "--json media/build/verdict.json; media/figures.py",
        "media/build/verdict.json, media/build/render.png"),
    "loop.png": (
        "Grade verdict per iteration (four real grade.sh runs on "
        "single-edit artifacts generated by media/figures.py) and the "
        "self-test kill rate per mutant, both measured.",
        "judge/grade.sh on each generated artifact; "
        "judge/selftest.sh --json media/build/selftest.json; media/figures.py",
        "media/build/loop_history.json, media/build/selftest.json"),
    "demo.mp4": (
        "The demo clip cut against media/STORYBOARD.md: the graded render "
        "and a real per-frame llvmpipe camera orbit of the same scene, the "
        "oracle rectangles, the real setup log, and the judge verdict and "
        "mutant kill matrix as a HUD over the still-moving render.",
        "media/make_media.sh (media/build_video.py)",
        "media/build/verdict.json, media/build/selftest.json, "
        "media/setup_progress.txt, media/build/setup_run.log"),
    "STORYBOARD.md": (
        "The slot table the video was cut against (written before the cut).",
        "hand-written to DEMO-STANDARD.md's media rules",
        "n/a (plan, not data)"),
    "REVIEW.json": (
        "The two blind vision-model verdicts on media/demo.mp4 from "
        "cookbook/tools/video_review_prompt.md (DEMO-STANDARD review panel).",
        "recorded from the panel run on media/demo.mp4",
        "media/demo.mp4"),
    "build_video.py": (
        "The video builder make_media.sh runs (frames + captions + cuts).",
        "hand-written; run by media/make_media.sh",
        "media/build/*.json, media/setup_progress.txt"),
    "figures.py": (
        "The result.png / loop.png builder.",
        "hand-written; run by media/make_media.sh",
        "media/build/verdict.json, media/build/selftest.json"),
    "write_result.py": (
        "Writes media/result.json (agent-next/result@1) from the grade "
        "JSON so the result card, the gallery and the storyboard carry the "
        "same numbers.",
        "media/make_media.sh (media/write_result.py)",
        "media/build/verdict.json, media/build/selftest.json"),
    "make_media.sh": (
        "Regenerates every file in this directory from the judge outputs.",
        "bash media/make_media.sh",
        "media/build/*.json"),
    "setup_progress.txt": (
        "The real [setup] progress lines of the setup.sh run this "
        "directory's media was built from.",
        "judge/setup.sh, logged by media/make_media.sh",
        "media/build/setup_run.log"),
    "result.json": (
        "One agent-next/result@1 manifest with the verdict, the per-gate "
        "numbers, the hero and the launch line.",
        "media/make_media.sh (media/write_result.py); "
        "python3 cookbook/tools/result.py check media/result.json",
        "media/build/verdict.json, media/build/selftest.json"),
}

SKIP_DIRS = ("master/", "build/", "__pycache__/")

man = []
for root, dirs, files in os.walk(MEDIA):
    dirs[:] = sorted(d for d in dirs
                     if not any(f"{d}/".startswith(p) or p.startswith(f"{d}/")
                                for p in SKIP_DIRS))
    for f in sorted(files):
        p = os.path.join(root, f)
        rel = os.path.relpath(p, MEDIA).replace(os.sep, "/")
        if rel == "MANIFEST.json":
            continue
        if any(rel.startswith(skip) for skip in SKIP_DIRS):
            continue
        if rel.endswith(".pyc"):
            continue
        shows, command, source = META.get(
            rel, ("(source file shipped with the demo)", "n/a", "n/a"))
        man.append({"file": rel,
                    "shows": shows,
                    "produced_by": command,
                    "source_data": source,
                    "size_bytes": os.path.getsize(p),
                    "sha256": hashlib.sha256(open(p, "rb").read()).hexdigest()})

doc = {
    "generated_at": __import__("datetime").datetime.utcnow().isoformat() + "Z",
    "commit": subprocess.check_output(
        ["git", "rev-parse", "HEAD"], cwd=MEDIA).decode().strip(),
    "note": "sha256 of the files as written by media/make_media.sh at the "
            "commit above; media/master/ (lossless masters), media/build/ "
            "(scratch judge outputs) and __pycache__ are git-ignored and "
            "deliberately not listed.",
    "files": man,
}
with open(os.path.join(MEDIA, "MANIFEST.json"), "w") as fh:
    json.dump(doc, fh, indent=2)
    fh.write("\n")

unknown = [m["file"] for m in man if m["shows"].startswith("(source file")]
if unknown:
    raise SystemExit(f"[make_media] MANIFEST has no description for: {unknown}")
print(f"[make_media] wrote MANIFEST.json ({len(man)} files)")
PY
echo "[make_media] DONE"