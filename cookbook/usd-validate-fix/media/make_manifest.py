#!/usr/bin/env python3
"""MANIFEST.json — for each file: what it shows, the command that produced it, the source data file, sha256."""

import hashlib
import json
import os
import sys

MEDIA = os.path.dirname(os.path.abspath(__file__))
DEMO = os.path.dirname(MEDIA)

def sha256(path):
    return hashlib.sha256(open(path, "rb").read()).hexdigest()

spec = {
    "result.png": {
        "what": "Key figure: left panel = task/traffic_cone_broken.usda (gray Band, no normals, 11 oracle errors, 7 FAILURE issues); right panel = examples/good/traffic_cone_fixed.usda (authored face-varying normals, 3/3 gates PASS, per-mesh normals==corners, max |norm|-1 deviation, zero-area faces, bbox deviation 0.0 cm). Bottom strip = the six seeded defects with real oracle error counts.",
        "command": "bash media/make_media.sh  (fig_result.py)",
        "source_data": "media/data/grade_good.json, media/data/grade_broken.json, media/data/mesh_good.json, media/data/mesh_broken.json",
    },
    "loop.png": {
        "what": "Self-test kill rate: per-mutant verdicts (the 12 known-bad single-edit mutants each with the gate that caught it and error count) plus kill-rate bar (12/12 = 100%, SPEC minimum 90%), determinism check, and which gate caught each mutant (validator 5, oracle 4, geometry 1, recount 2).",
        "command": "bash media/make_media.sh  (fig_loop.py)",
        "source_data": "media/data/grade_*.json (12 mutants + good + broken), media/data/selftest_output.txt",
    },
    "demo.mp4": {
        "what": "25-60 s video: (0-2 s) hook - finished repaired cone fills frame; (2-10 s) input->output - broken beside repaired asset; (10-35 s) escalate - camera orbit with gate HUD; (35-45 s) proof - judge PASS + mutant kill matrix as HUD; (last 3 s) end card - one-line launch command. Lossless crf 0 master in git-ignored media/master/.",
        "command": "bash media/make_media.sh  (make_video.py + ffmpeg)",
        "source_data": "media/data/grade_*.json, media/data/selftest_output.txt, media/data/mesh_good.json, media/data/mesh_broken.json",
    },
    "MANIFEST.json": {
        "what": "This manifest: sha256, what, command, source_data for each shipped media file.",
        "command": "bash media/make_media.sh  (make_manifest.py)",
        "source_data": "media/result.png, media/loop.png, media/demo.mp4",
    },
    "result.json": {
        "what": "Agent-next result manifest (schema agent-next/result@1) driving the in-chat result card, demo gallery and storyboard: headline, verdict PASS, gate measurements, key numbers, hero/gallery entries, launch command, receipt path, sandbox commit.",
        "command": "bash media/make_media.sh  (make_result_json.py)",
        "source_data": "media/data/grade_good.json, RECEIPT.md",
    },
    "STORYBOARD.md": {
        "what": "Planned storyboard as filled-in slot table: what fills each frame, source data/command, caption text — written before the video is cut; the video is judged against it.",
        "command": "bash media/make_media.sh  (make_storyboard.py)",
        "source_data": "media/data/grade_*.json, media/demo.mp4",
    },
    "REVIEW.json": {
        "what": "Two blind judge verdicts on demo.mp4 (vision models from different families, no README/context), scoring visual_quality, wow, clarity, payoff_visible_by_s, understandable_muted. Pass = both >= thresholds.",
        "command": "bash media/make_media.sh  (make_review.py)",
        "source_data": "media/demo.mp4",
    },
}

entries = []
for fname, meta in spec.items():
    p = os.path.join(MEDIA, fname)
    if os.path.exists(p):
        entries.append({
            "file": fname,
            "what": meta["what"],
            "command": meta["command"],
            "source_data": meta["source_data"],
            "sha256": sha256(p),
            "bytes": os.path.getsize(p)
        })
    else:
        print(f"WARNING: {fname} not found, skipping", file=sys.stderr)

with open(os.path.join(MEDIA, "MANIFEST.json"), "w") as f:
    json.dump({
        "demo": "cookbook/usd-validate-fix",
        "note": "every number plotted comes from judge output files regenerated by make_media.sh (seed 20261015)",
        "files": entries
    }, f, indent=2)
    f.write("\n")

for e in entries:
    print(f"  {e['file']:<12} {e['bytes']:>9} bytes  {e['sha256'][:16]}...")

print("make_manifest: done")
