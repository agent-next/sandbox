#!/usr/bin/env python3
"""Regenerate judge/requirements.lock with real sha256 hashes.

Drop-in replacement for genlock.py (kept for provenance): queries the PyPI
JSON API with a pip-like User-Agent and the PyTorch CPU wheel index, collects
the sha256 of every supported wheel (CPython 3.10-3.13, x86-64 Linux), and
writes a pip --require-hashes compatible lock file.

Usage: python3 genlock2.py > requirements.lock
"""

import json
import re
import sys
import urllib.request

PYPI = "https://pypi.org/pypi"
TORCH_CPU = "https://download.pytorch.org/whl/cpu/torch/"

PACKAGES = [
    ("torch", "2.3.1", ["cp{pyver}-cp{pyver}-linux_x86_64.whl",
                        "cp{pyver}-cp{pyver}-manylinux_2_28_x86_64.whl"]),
    ("sentence-transformers", "2.7.0", None),
    ("faiss-cpu", "1.8.0", None),
    ("numpy", "1.26.4", None),
    ("scipy", "1.13.1", None),
    ("scikit-learn", "1.5.2", None),
    ("huggingface-hub", "0.23.4", None),
    ("transformers", "4.42.1", None),
    ("tokenizers", "0.19.1", None),
    ("safetensors", "0.4.3", None),
    ("filelock", "3.15.3", None),
    ("typing-extensions", "4.12.2", None),
    ("sympy", "1.13.0", None),
    ("networkx", "3.3", None),
    ("jinja2", "3.1.4", None),
    ("MarkupSafe", "2.1.5", None),
    ("mpmath", "1.3.0", None),
    ("fsspec", "2024.6.0", None),
    ("packaging", "24.1", None),
    ("pyyaml", "6.0.1", None),
    ("regex", "2024.5.15", None),
    ("tqdm", "4.66.4", None),
    ("requests", "2.32.3", None),
    ("Pillow", "10.3.0", None),
]

PYTHON_VERSIONS = ["310", "311", "312", "313"]

UA = {"User-Agent": "pip/25.0.1"}


def fetch(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())


def fetch_text(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode()


def main():
    lines = [
        "#",
        "# pinned cpu closure for the gpu-embed-rag-index judge",
        "# generated by judge/genlock2.py from live PyPI / PyTorch-index hashes",
        "# cp310-312, x86-64 linux (torch 2.3.1+cpu has no cp313 wheel)",
        "# torch cpu wheels live on the pytorch cpu index; setup.sh passes",
        "# --extra-index-url https://download.pytorch.org/whl/cpu (kept out of",
        "# this file: an option line here makes pip ignore the indented",
        "# --hash lines that follow it).",
        "#",
    ]
    missing = 0
    for name, version, wheel_tmpl in PACKAGES:
        if wheel_tmpl:
            # torch cpu wheels live on the PyTorch index; emit one pin with
            # the hash of every supported CPython wheel (cp310-312 for
            # torch 2.3.1+cpu — cp313 wheels start at torch 2.4)
            html = fetch_text(TORCH_CPU)
            torch_shas = []
            for pyver in PYTHON_VERSIONS:
                for tmpl_wheel in wheel_tmpl:
                    fname = tmpl_wheel.replace("{pyver}", pyver)
                    m = re.search(
                        r'torch-' + re.escape(version) + r'%2Bcpu-' +
                        re.escape(fname) + r'#sha256=([a-f0-9]{64})',
                        html)
                    if m:
                        torch_shas.append(m.group(1))
                        break
            if not torch_shas:
                print(f"error: no sha256 for torch {version}", file=sys.stderr)
                missing += 1
            else:
                lines.append(f"{name}=={version}+cpu")
                lines.extend(f"  --hash=sha256:{s}" for s in torch_shas)
        else:
            req = urllib.request.Request(f"{PYPI}/{name}/{version}/json", headers=UA)
            try:
                with urllib.request.urlopen(req, timeout=60) as r:
                    data = json.loads(r.read())
            except Exception as e:
                print(f"error: {name} {version}: {e}", file=sys.stderr)
                raise
            lines.append(f"{name}=={version}")
            got = 0
            for f in data["urls"]:
                if f["packagetype"] != "bdist_wheel":
                    continue
                fn = f["filename"].lower()
                # supported: pure-python wheels, or linux x86-64 wheels
                # tagged for cp310-cp313
                pure = fn.endswith("-none-any.whl")
                cp = any(f"-cp{p}-" in fn for p in PYTHON_VERSIONS)
                linux = "x86_64" in fn
                if not (pure or (cp and linux)):
                    continue
                lines.append(f"  --hash=sha256:{f['digests']['sha256']}")
                got += 1
            if not got:
                print(f"error: no supported wheels for {name} {version}", file=sys.stderr)
                missing += 1
    if missing:
        print(f"error: {missing} package(s) missing hashes", file=sys.stderr)
        raise SystemExit(1)
    print("\n".join(lines))


if __name__ == "__main__":
    main()
