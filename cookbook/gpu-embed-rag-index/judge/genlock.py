#!/usr/bin/env python3
"""Generate judge/requirements.lock from live PyPI / PyTorch-index hashes.

Usage: python3 genlock.py > requirements.lock

Queries the PyPI JSON API for each package's pinned version, collects the
sha256 of every wheel for the supported CPython versions (3.10-3.13, x86-64
Linux), and writes a pip --require-hashes compatible lock file. For torch,
queries the PyTorch CPU wheel index instead of PyPI.
"""

import json
import sys
import urllib.request

PYPI = "https://pypi.org/pypi"
TORCH_CPU = "https://download.pytorch.org/whl/cpu/torch/"

PACKAGES = [
    ("torch", "2.3.1", "torch-cp{pyver}-cp{pyver}-manylinux_2_28_x86_64.whl"),
    ("sentence-transformers", "2.7.0", None),
    ("faiss-cpu", "1.8.0", None),
    ("numpy", "1.26.4", None),
    ("scipy", "1.13.1", None),
    ("scikit-learn", "1.5.2", None),
    ("huggingface-hub", "0.23.4", None),
    ("transformers", "4.41.3", None),
    ("tokenizers", "0.19.1", None),
    ("safetensors", "0.4.3", None),
    ("filelock", "3.15.3", None),
    ("typing-extensions", "4.12.2", None),
    ("sympy", "1.13.0", None),
    ("networkx", "3.3", None),
    ("jinja2", "3.1.4", None),
    ("MarkupSafe", "2.1.5", None),
    ("mpmath", "1.3.0", None),
    ("fsspec", "2024.6.0", None),
    ("packaging", "24.1", None),
    ("pyyaml", "6.0.1", None),
    ("regex", "2024.5.15", None),
    ("tqdm", "4.66.4", None),
    ("requests", "2.32.3", None),
    ("Pillow", "10.3.0", None),
]

PYTHON_VERSIONS = ["310", "311", "312", "313"]


def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "genlock/1.0"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.loads(r.read())


def torch_wheel_url(version, pyver, wheel_tmpl):
    fname = wheel_tmpl.format(pyver=pyver)
    return f"{TORCH_CPU}torch-{version}%2Bcpu-{fname}"


def main():
    lines = [
        "#",
        "# pinned cpu closure for the gpu-embed-rag-index judge",
        "# generated by genlock.py from live PyPI / PyTorch-index hashes",
        "# cp310-313, x86-64 linux",
        "#",
    ]
    for name, version, wheel_tmpl in PACKAGES:
        if wheel_tmpl:
            for pyver in PYTHON_VERSIONS:
                url = torch_wheel_url(version, pyver, wheel_tmpl)
                try:
                    req = urllib.request.Request(url, method="HEAD",
                                                 headers={"User-Agent": "genlock/1.0"})
                    with urllib.request.urlopen(req, timeout=60) as r:
                        sha = r.headers.get("X-Checksum-Sha256", "")
                    if not sha:
                        # fallback: fetch the HTML index and grep
                        html = fetch(TORCH_CPU).decode()
                        import re
                        m = re.search(
                            r'torch-' + re.escape(version) + r'%2Bcpu-cp' + pyver +
                            r'-cp' + pyver + r'-manylinux_2_28_x86_64\.whl#sha256=([a-f0-9]{64})',
                            html)
                        if not m:
                            print(f"warning: no sha256 for {name} cp{pyver}", file=sys.stderr)
                            continue
                        sha = m.group(1)
                    lines.append(f"{name}=={version}")
                    lines.append(f"  --hash=sha256:{sha}")
                except Exception as e:
                    print(f"warning: {name} cp{pyver}: {e}", file=sys.stderr)
        else:
            data = fetch(f"{PYPI}/{name}/{version}")
            lines.append(f"{name}=={version}")
            for f in data["urls"]:
                if f["packagetype"] == "bdist_wheel" and "x86_64" in f["filename"].lower():
                    lines.append(f"  --hash=sha256:{f['digests']['sha256']}")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
