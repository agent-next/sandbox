"""Hash the shipped media and name its exact, regenerable inputs."""

import hashlib
import json
from pathlib import Path
import platform
import subprocess

import matplotlib
import numpy

HERE = Path(__file__).resolve().parent
DEMO = HERE.parent


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    probe = json.loads(subprocess.check_output([
        "ffprobe", "-v", "error", "-show_format", "-show_streams", "-of", "json",
        str(HERE / "demo.mp4"),
    ]))
    video = probe["streams"][0]
    assert video["codec_name"] == "h264" and video["pix_fmt"] == "yuv420p"
    assert (video["width"], video["height"], video["r_frame_rate"]) == (1920, 1080, "30/1")
    assert 20 <= float(probe["format"]["duration"]) <= 60
    assert int(probe["format"]["size"]) < 8_000_000
    sources = [
        "judge/spec.json", "judge/_grade.py", "judge/grade.sh", "judge/setup.sh",
        "judge/selftest.sh", "judge/mutants.py", "judge/ref_sim.py",
        "judge/requirements.lock", "examples/good/sim.py", "examples/good/loop.json",
        "examples/loop.py", "media/requirements.txt", "media/collect.py",
        "media/render.py", "media/manifest.py", "media/make_media.sh", "media/test_media.py",
        "media/data/grade.json", "media/data/selftest.txt",
    ] + [f"media/data/traj_{s}.csv" for s in
         ("drop", "incline_slide", "incline_stick", "pendulum")]
    descriptions = {
        "result.png": (
            "Four panels: measured drop/contact vs free fall; slide/stick vs "
            "analytic displacement; pendulum with SPEC-period cosine guide; "
            "oracle error normalized to each SPEC limit (stick uses travel/20 mm).",
            ["media/data/traj_*.csv", "media/data/grade.json", "judge/spec.json",
             "judge/_grade.py"]),
        "loop.png": (
            "Recorded draft replay: passing scenes per iteration and overall "
            "verdict; real selftest rejection bars for good plus eight mutants, "
            "labelled with the observed failing gates.",
            ["examples/good/loop.json", "media/data/selftest.txt"]),
        "demo.mp4": (
            "28 s CSV-driven sphere drop, sliding/sticking boxes and swinging "
            "pendulum; analytic ghosts/readouts, ending on the judge PASS table. "
            "Web crf 18 / preset slow from ignored crf 0 media/master/demo.mp4.",
            ["media/data/traj_*.csv", "media/data/grade.json", "judge/spec.json",
             "judge/_grade.py", "media/data/selftest.txt"]),
    }
    files = []
    for name, (what, data) in descriptions.items():
        path = HERE / name
        files.append({
            "file": name, "what": what,
            "command": "bash cookbook/sim-engine-arena/media/make_media.sh",
            "source_data": data, "sha256": digest(path), "bytes": path.stat().st_size,
        })
    manifest = {
        "demo": "cookbook/sim-engine-arena", "seed": 0,
        "note": "No invented measurements. CSVs are regenerated by the good "
        "artifact and their oracle metrics asserted exactly equal to the "
        "full-run grade. data/grade.json excludes only timing. The judge is "
        "copied unchanged to ignored scratch before setup (which writes VERSIONS.txt). "
        "CSV dumps and toolchains are ignored, not shipped.",
        "files": files, "source_sha256": {s: digest(DEMO / s) for s in sources},
        "toolchain": {
            "python": platform.python_version(), "matplotlib": matplotlib.__version__,
            "numpy_rendering": numpy.__version__,
            "judge": (HERE / "data/versions.txt").read_text().splitlines()[0].lstrip("# "),
            "ffmpeg": subprocess.check_output(
                ["ffmpeg", "-version"], text=True).splitlines()[0].split()[2],
        },
        "video": {k: video[k] for k in ("codec_name", "width", "height",
                                      "r_frame_rate", "pix_fmt", "nb_frames")},
        "duration_s": float(probe["format"]["duration"]),
    }
    (HERE / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print("MANIFEST.json: hashes written; video meets duration/size/format limits")


if __name__ == "__main__":
    main()
