#!/usr/bin/env python3
"""media/loop.png -- the agent loop and the self-test kill-rate bar.

Left: the judge's verdict per iteration of a real fix sequence.  Each
iteration is an artifact generated by media/make_loop_artifacts.py and
graded for real by judge/grade.sh --seed 1; the JSON verdicts live in
media/data/loop/iter<N>.json and the label on each bar is the gate that
failed (or "PASS"), taken from that verdict.  The bar height is the number
of gates still failing, so the loop visibly converges to zero.

Right: the self-test kill rate -- the known-good artifact versus each of the
13 single-edit mutants, from media/data/verdicts/*.json.  A green cell is a
mutant the judge killed (exit 1); the text is the gate that killed it.

Usage: fig_loop.py <demo-dir>
"""

import json
import sys
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.patches import Patch  # noqa: E402

GATES = ["artifact", "determinism", "zero_melt", "crossing",
         "final_volume", "shape", "figure"]


def failing_gates(verdict):
    """Names of gates with passed=false (ignores _meta)."""
    return [g for g in GATES
            if not verdict["gates"].get(g, {}).get("passed", True)]


def main():
    demo = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent.parent
    media = demo / "media"
    loop_dir = media / "data" / "loop"
    verdict_dir = media / "data" / "verdicts"

    fig, (ax, bx) = plt.subplots(1, 2, figsize=(12.5, 5.4), dpi=200,
                                 gridspec_kw={"width_ratios": [1.0, 1.55]})

    # --- left: the agent loop -------------------------------------------
    iters, labels, heights, colors = [], [], [], []
    for n in range(1, 6):
        v = json.loads((loop_dir / f"iter{n}.json").read_text())
        fails = failing_gates(v)
        iters.append(n)
        if v["passed"]:
            labels.append("PASS")
            colors.append("#2E7D32")
        else:
            labels.append(v.get("failed_gate", "?"))
            colors.append("#C0392B")
        heights.append(len(fails))
    bars = ax.bar(iters, heights, color=colors, width=0.62)
    for bar, lab, h in zip(bars, labels, heights):
        ax.text(bar.get_x() + bar.get_width() / 2,
                h + 0.08 if h else 0.08, lab, ha="center", va="bottom",
                fontsize=8.5, rotation=0)
    ax.set_xticks(iters)
    ax.set_xticklabels([f"iter {n}" for n in iters])
    ax.set_ylim(0, max(heights) + 1.0)
    ax.set_ylabel("gates still failing")
    ax.set_title("Agent loop: one real bug fixed per iteration\n"
                 "(label = the gate the judge failed it on)")
    ax.grid(axis="y", alpha=0.3)
    ax.legend(handles=[Patch(color="#C0392B", label="judge rejects"),
                       Patch(color="#2E7D32", label="all gates pass")],
              loc="upper right", fontsize=8.5)

    # --- right: the self-test kill rate ---------------------------------
    mutants = sorted(p.stem for p in verdict_dir.glob("*.json")
                     if p.stem != "good")
    names, gates, killed = [], [], []
    for m in mutants:
        v = json.loads((verdict_dir / f"{m}.json").read_text())
        names.append(m)
        gates.append(v.get("failed_gate", "PASS") if not v["passed"] else "PASS")
        killed.append(not v["passed"])
    good = json.loads((verdict_dir / "good.json").read_text())

    # One row per mutant: a green cell if killed, red if it survived.
    ypos = list(range(len(names)))
    cell = [[1] for _ in names]
    bx.imshow(cell, cmap=None, aspect="auto", vmin=0, vmax=1,
              extent=(-0.5, 0.5, -0.5, len(names) - 0.5))
    bx.clear()
    for i, (nm, gt, k) in enumerate(zip(names, gates, killed)):
        bx.barh(i, 1, color="#2E7D32" if k else "#C0392B", height=0.7)
        bx.text(0.02, i, nm, va="center", ha="left", fontsize=8,
                color="white", fontweight="bold")
        bx.text(0.98, i, f"killed by {gt}" if k else "SURVIVED",
                va="center", ha="right", fontsize=8, color="white")
    bx.set_xlim(0, 1)
    bx.set_ylim(-0.6, len(names) - 0.4)
    bx.set_yticks([])
    bx.set_xticks([])
    rate = sum(killed)
    good_state = "PASS" if good["passed"] else "FAIL"
    bx.set_title(f"Self-test: known-good examples/good {good_state}; "
                 f"{rate}/{len(names)} mutants killed = "
                 f"{rate / len(names):.0%}  (required ≥ 90 %)")
    bx.legend(handles=[Patch(color="#2E7D32", label="killed (judge exit 1)"),
                       Patch(color="#C0392B", label="survived")],
              loc="upper center", bbox_to_anchor=(0.5, -0.03), ncol=2,
              fontsize=8.5, framealpha=0.95)

    fig.suptitle("climate-glacier-model — the judge cannot be fooled",
                 y=1.005, fontsize=11)
    fig.tight_layout()
    out = media / "loop.png"
    fig.savefig(out, dpi=200, bbox_inches="tight")
    plt.close(fig)
    print(f"wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
