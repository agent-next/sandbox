#!/usr/bin/env python3
"""Known-bad artifacts for the backtest-equity judge: single-edit mutants.

Usage: mutants.py <out_dir>

Each mutant is one edit away from the known-good artifact in examples/good,
covering the failure class its name says it covers:

  lookahead-shift   declares a 2-bar lag while trading a 1-bar signal
                    -> G5 lookahead negative control
  lookahead-signal  actually lags the signal one bar later than it declares
                    -> G2 final-equity oracle
  sharpe-tamper     reports a Sharpe that disagrees with returns.csv -> G3
  equity-tamper     reports a final equity 20 % off the reference     -> G2
  mdd-tamper        reports a max drawdown that disagrees with the CSV -> G4
  fixture-drift     one pinned price altered                          -> G1
  cost-tamper       reports costs as 0 bps                            -> G2/G6
  returns-drift     the CSV drifts away from the metrics it claims   -> G3/G4
  short-history     fewer than 252 return rows                        -> G6
  tiny-figure       equity.png below 800x600                          -> G6

Writes one directory per mutant, then prints one name per line.
"""

from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GOOD = HERE.parent / "examples" / "good"

TEXT_FILES = ("ohlcv.csv", "returns.csv", "metrics.json")
MIN_PNG_W, MIN_PNG_H = 800, 600


def load_good():
    files = {}
    for name in TEXT_FILES:
        files[name] = (GOOD / name).read_text(encoding="utf-8")
    files["equity.png"] = (GOOD / "equity.png").read_bytes()
    return files


def emit(outdir: Path, name: str, files: dict) -> str:
    d = outdir / name
    d.mkdir(parents=True, exist_ok=True)
    for name_, blob in files.items():
        if isinstance(blob, str):
            (d / name_).write_text(blob, encoding="utf-8", newline="")
        else:
            (d / name_).write_bytes(blob)
    (d / "backtest.py").write_text(
        "# mutant of examples/good/backtest.py (generated by judge/mutants.py)\n"
        "# kept so the artifact directory is self-describing; the judge\n"
        "# never executes it\n", encoding="utf-8")
    return name


def png_claim(blob: bytes, width: int, height: int) -> bytes:
    """Rewrite a PNG's IHDR to claim a different size (G6 sizes the figure
    from the IHDR, so a figure that claims to be small must be rejected)."""
    pos = blob.index(b"IHDR")
    return blob[:pos] + struct.pack(">II", width, height) + blob[pos + 8:]


def retune(metrics_text: str, **changes) -> str:
    m = json.loads(metrics_text)
    m.update(changes)
    return json.dumps(m, indent=2) + "\n"


def scale_last_return(text: str, factor: float) -> str:
    """Scale the final return row by `factor`: the CSV drifts away from the
    metrics that claim to describe it."""
    lines = text.splitlines()
    head, last = lines[0], lines[-1]
    d, r = last.split(",")
    scaled = float(r) * factor
    lines[-1] = f"{d},{scaled:.10e}"
    return "\n".join(lines) + "\n"


def main() -> int:
    outdir = Path(sys.argv[1])
    outdir.mkdir(parents=True, exist_ok=True)
    good = load_good()
    made = []

    # --- G5: declares a 2-bar lag while the reference at 2 bars differs ---
    m = dict(good)
    m["metrics.json"] = retune(good["metrics.json"], lookahead_shift=2)
    made.append(emit(outdir, "lookahead-shift", m))

    # --- G2: actually trades a 2-bar lag, so the equity disagrees with
    #         the reference run at the declared 1-bar lag.
    m = dict(good)
    lines = good["returns.csv"].splitlines(keepends=True)
    rows = [l.rstrip("\n").split(",") for l in lines[1:]]
    rets = [float(r[1]) for r in rows]
    lagged = [0.0] * len(rets)
    for i in range(1, len(rets)):
        lagged[i] = rets[i - 1]
    m["returns.csv"] = "date,ret\n" + "".join(
        f"{r[0]},{v:.10e}\n" for r, v in zip(rows, lagged))
    made.append(emit(outdir, "lookahead-signal", m))

    # --- G3: reports a Sharpe that disagrees with its own returns.csv -----
    m = dict(good)
    m["metrics.json"] = retune(good["metrics.json"],
                               sharpe=json.loads(good["metrics.json"])["sharpe"] + 0.01)
    made.append(emit(outdir, "sharpe-tamper", m))

    # --- G2: reports a final equity 20 % off the reference ---------------
    m = dict(good)
    m["metrics.json"] = retune(good["metrics.json"],
                               final_equity=json.loads(good["metrics.json"])["final_equity"] * 0.8)
    made.append(emit(outdir, "equity-tamper", m))

    # --- G4: reports a max drawdown that disagrees with the CSV ----------
    m = dict(good)
    m["metrics.json"] = retune(good["metrics.json"], max_drawdown=0.30)
    made.append(emit(outdir, "mdd-tamper", m))

    # --- G1: one pinned price altered (the no-lookahead data gate) -------
    m = dict(good)
    lines = good["ohlcv.csv"].splitlines(keepends=True)
    idx = next(i for i, l in enumerate(lines) if "132.2476" in l)
    lines[idx] = lines[idx].replace("132.2476", "132.4476", 1)
    m["ohlcv.csv"] = "".join(lines)
    made.append(emit(outdir, "fixture-drift", m))

    # --- G2/G6: reports costs as 0 bps -----------------------------------
    m = dict(good)
    m["metrics.json"] = retune(good["metrics.json"], cost_bps=0.0)
    made.append(emit(outdir, "cost-tamper", m))

    # --- G3/G4: the CSV drifts away from the metrics it claims -----------
    m = dict(good)
    m["returns.csv"] = scale_last_return(good["returns.csv"], 0.5)
    if m["returns.csv"] == good["returns.csv"]:
        raise SystemExit("returns-drift: scaling the last return changed nothing")
    made.append(emit(outdir, "returns-drift", m))

    # --- G6: fewer than 252 return rows ----------------------------------
    m = dict(good)
    m["returns.csv"] = "".join(good["returns.csv"].splitlines(keepends=True)[:200])
    made.append(emit(outdir, "short-history", m))

    # --- G6: equity.png below the minimum figure size -------------------
    m = dict(good)
    m["equity.png"] = png_claim(good["equity.png"], 640, 480)
    made.append(emit(outdir, "tiny-figure", m))

    print("\n".join(made))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
