#!/usr/bin/env python3
"""The backtest-equity judge.

grade.sh <artifact> [--seed N] [--json out.json]

Prints one JSON verdict and exits 0 only if every gate passes. The judge
never imports or executes anything from the artifact under test: all oracle
math runs in judge/reference.py on the judge's own copies of the data.

Gates (all numeric and deterministic; SPEC.md has the prose):

  G1 fixture_integrity   sha256 of the artifact's ohlcv.csv == the manifest
  G2 final_equity_oracle |artifact - reference| / reference <= 0.1 %
  G3 sharpe_consistency   |metrics.sharpe - sharpe(artifact's returns.csv)| < 1e-6
  G4 max_drawdown         |metrics.max_drawdown - mdd(artifact's returns.csv)| <= 1e-6
  G5 lookahead_control    reference with shift+1 must differ by > 1e-9
                          relative, and the artifact must declare the shift
  G6 schema_sanity        row count / dates / no NaNs / equity.png size /
                          required metrics keys and values

Wall time lives under "timing"; everything else is a pure function of the
pinned fixture, the artifact and --seed, so two runs with the same seed are
byte-identical excluding that key (checked by selftest.sh).

Usage inside a mutation-testing loop: mutants.py writes a corrupted
artifact, this module reads it, prints the verdict.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import re
import shutil
import struct
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEMO = HERE.parent
sys.path.insert(0, str(HERE))

import reference  # noqa: E402  (the blind oracle; stdlib only)

# --- pinned fixture -------------------------------------------------------
# sha256 of the exact ohlcv.csv the demo was built from, as generated by
# tools/make_fixture.py --seed 20261014.  G1 compares against this value.
FIXTURE_SHA256 = "227517225b7f4978c8c5c4092d40a91af9a5cbd82859c82c7516f92efb881821"
FIXTURE_NAME = "ohlcv.csv"
FIXTURE_COLS = ("date", "open", "high", "low", "close", "volume")

REQUIRED_METRIC_KEYS = (
    "final_equity", "total_return", "n_days", "n_trades", "max_drawdown",
    "sharpe", "volatility_ann", "mean_daily_ret", "risk_free_rate",
    "cost_bps", "lookahead_shift",
)

EQUITY_PNG_MIN_W = 800
EQUITY_PNG_MIN_H = 600
MIN_RETURN_ROWS = 252

# Tolerances, from SPEC.md.
FINAL_EQUITY_REL_TOL = 1e-3          # 0.1 %
SHARPE_ABS_TOL = 1e-6
MDD_ABS_TOL = 1e-6
LOOKAHEAD_REL_TOL = 1e-9


def _hash(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _num(x):
    """A finite float, or None.  Bools and non-finite values are rejected."""
    if isinstance(x, bool):
        return None
    try:
        v = float(x)
    except (TypeError, ValueError):
        return None
    return v if math.isfinite(v) else None


def read_pinned_closes():
    """The demo's own fixture, read by the judge (never the artifact's)."""
    path = DEMO / "tools" / "data" / FIXTURE_NAME
    dates, closes = [], []
    with path.open(newline="") as fh:
        header = fh.readline().rstrip("\n").rstrip("\r").split(",")
        if tuple(header) != FIXTURE_COLS:
            raise ValueError(f"pinned fixture header is {header!r}")
        for line in fh:
            line = line.rstrip("\n").rstrip("\r")
            if not line:
                continue
            parts = line.split(",")
            dates.append(parts[0])
            closes.append(float(parts[4]))
    return dates, closes


def png_size(path: Path):
    """(width, height) of a PNG read from its IHDR; None if not a PNG.

    Layout: 8-byte signature, then the IHDR chunk = 4-byte length, the
    4-byte tag "IHDR", then width (4 bytes) and height (4 bytes) big-endian.
    """
    with path.open("rb") as fh:
        sig = fh.read(8)
        if sig != b"\x89PNG\r\n\x1a\n":
            return None
        chunk = fh.read(16)          # length + tag + width + height
        if len(chunk) < 16 or chunk[4:8] != b"IHDR":
            return None
        w, h = struct.unpack(">II", chunk[8:16])
        return w, h


def read_returns_csv(path: Path):
    """(dates, returns) from an artifact's returns.csv.  Raises on bad data."""
    with path.open(newline="", encoding="utf-8") as fh:
        rows = fh.read().splitlines()
    if not rows:
        raise ValueError("returns.csv is empty")
    header = rows[0].rstrip("\r").split(",")
    if header[:2] != ["date", "ret"]:
        raise ValueError(f"returns.csv header is {header!r}, expected date,ret")
    dates, rets = [], []
    for i, line in enumerate(rows[1:], start=2):
        line = line.rstrip("\r")
        if not line:
            raise ValueError(f"returns.csv line {i} is blank")
        parts = line.split(",")
        if len(parts) != 2:
            raise ValueError(f"returns.csv line {i} has {len(parts)} fields")
        d = parts[0]
        try:
            r = float(parts[1])
        except ValueError:
            raise ValueError(f"returns.csv line {i}: ret {parts[1]!r} is not a number")
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", d):
            raise ValueError(f"returns.csv line {i}: date {d!r} is not ISO YYYY-MM-DD")
        dates.append(d)
        rets.append(r)
    return dates, rets


def sharpe_from_returns(rets):
    n = len(rets)
    if n < 2:
        raise ValueError("fewer than 2 return rows")
    mean = sum(rets) / n
    var = sum((r - mean) ** 2 for r in rets) / (n - 1)
    std = math.sqrt(var)
    if std <= 0.0:
        raise ValueError("returns.csv has zero variance")
    return mean / std * math.sqrt(reference.TRADING_DAYS)


def max_drawdown_from_returns(rets):
    """Max drawdown of the equity curve implied by net daily returns."""
    equity = 1.0
    peak = 1.0
    worst = 0.0
    for r in rets:
        equity *= 1.0 + r
        if equity > peak:
            peak = equity
        dd = 1.0 - equity / peak
        if dd > worst:
            worst = dd
    return worst


def grade(artifact_dir: Path, seed: int) -> dict:
    t0 = time.monotonic()
    artifact = Path(artifact_dir)
    if not artifact.is_dir():
        raise SystemExit(f"not a directory: {artifact} (grade.sh takes the "
                         f"artifact directory)")
    gates = {}

    # --- the artifact is copied before grading so that nothing it contains
    # can touch the judge; selftest.sh additionally checksums judge/ around
    # every run and fails closed if anything changed.
    tmp = Path(tempfile.mkdtemp(prefix="backtest-judge-"))
    try:
        src = tmp / "artifact"
        shutil.copytree(artifact, src)

        def fail(code: str, detail: str):
            gates[code] = {"pass": False, "detail": detail}

        # ---- G6 schema sanity, evaluated first so that a malformed
        # artifact is reported as such and not as a numeric disagreement.
        metrics = None
        dates = rets = None
        try:
            ohlcv_path = src / "ohlcv.csv"
            if not ohlcv_path.is_file():
                raise ValueError("ohlcv.csv is missing from the artifact")
            with ohlcv_path.open(newline="", encoding="utf-8") as fh:
                header = fh.readline().rstrip("\r\n").split(",")
                if tuple(header) != FIXTURE_COLS:
                    raise ValueError(f"ohlcv.csv header is {header!r}, "
                                     f"expected {list(FIXTURE_COLS)}")
                art_closes = []
                for i, line in enumerate(fh, start=2):
                    parts = line.rstrip("\r\n").split(",")
                    if len(parts) not in (6, 7):
                        raise ValueError(f"ohlcv.csv line {i}: {len(parts)} fields")
                    art_closes.append(float(parts[4]))
            if len(art_closes) < 1:
                raise ValueError("ohlcv.csv has no data rows")

            raw_metrics = json.loads((src / "metrics.json").read_text(encoding="utf-8"))
            if not isinstance(raw_metrics, dict):
                raise ValueError("metrics.json is not a JSON object")
            missing = [k for k in REQUIRED_METRIC_KEYS if k not in raw_metrics]
            if missing:
                raise ValueError(f"metrics.json is missing keys {missing}")
            metrics = {k: _num(raw_metrics[k]) for k in REQUIRED_METRIC_KEYS}
            bad = {k: raw_metrics[k] for k, v in metrics.items() if v is None}
            if bad:
                raise ValueError(f"metrics.json has non-numeric values for {sorted(bad)}")
            if raw_metrics.get("cost_bps") != 10.0:
                raise ValueError(f"metrics.json cost_bps is "
                                 f"{raw_metrics.get('cost_bps')!r}, must be 10.0")
            shift = metrics["lookahead_shift"]
            if shift != int(shift) or shift < 0:
                raise ValueError(f"lookahead_shift {shift} must be an integer >= 0")
            if metrics["risk_free_rate"] != 0.0:
                raise ValueError(f"risk_free_rate must be 0.0, got {metrics['risk_free_rate']}")

            dates, rets = read_returns_csv(src / "returns.csv")
            if len(rets) < MIN_RETURN_ROWS:
                raise ValueError(f"returns.csv has {len(rets)} rows, need >= {MIN_RETURN_ROWS}")
            if any(dates[i] >= dates[i + 1] for i in range(len(dates) - 1)):
                raise ValueError("returns.csv dates are not strictly increasing")
            if any(not math.isfinite(r) for r in rets):
                raise ValueError("returns.csv has NaN or infinite returns")

            png = src / "equity.png"
            if not png.is_file():
                raise ValueError("equity.png is missing from the artifact")
            size = png_size(png)
            if size is None:
                raise ValueError("equity.png is not a valid PNG")
            w, h = size
            if w < EQUITY_PNG_MIN_W or h < EQUITY_PNG_MIN_H:
                raise ValueError(f"equity.png is {w}x{h}, need >= "
                                 f"{EQUITY_PNG_MIN_W}x{EQUITY_PNG_MIN_H}")

            if metrics["n_days"] != len(rets):
                raise ValueError(f"metrics.json n_days {metrics['n_days']} != "
                                 f"returns.csv rows {len(rets)}")
            if metrics["n_trades"] < 0:
                raise ValueError("n_trades must be >= 0")

            gates["G6_schema_sanity"] = {"pass": True, "detail": (
                f"{len(rets)} return rows ({dates[0]}..{dates[-1]}), dates strictly "
                f"increasing, no NaNs; equity.png {w}x{h}; metrics.json keys ok, "
                f"cost_bps 10.0, lookahead_shift {shift}")}
        except (OSError, ValueError, json.JSONDecodeError) as exc:
            fail("G6_schema_sanity", str(exc))

        ref_shift = None
        if isinstance(metrics, dict):
            ref_shift = int(metrics["lookahead_shift"])

        # ---- G1 fixture integrity -----------------------------------------
        try:
            ohlcv_path = src / "ohlcv.csv"
            if not ohlcv_path.is_file():
                raise ValueError("ohlcv.csv is missing from the artifact")
            got = _hash(ohlcv_path)
            if got != FIXTURE_SHA256:
                raise ValueError(
                    f"artifact ohlcv.csv sha256 {got} != pinned fixture "
                    f"{FIXTURE_SHA256} (the no-lookahead data gate)")
            gates["G1_fixture_integrity"] = {"pass": True, "detail": (
                f"ohlcv.csv sha256 {got} == pinned fixture")}
        except (OSError, ValueError) as exc:
            fail("G1_fixture_integrity", str(exc))

        # ---- G2/G5: the blind reference, at the declared and lag+1 shifts -
        ref = ref_lag = None
        ref_info = None
        try:
            if ref_shift is None:
                raise ValueError("no usable lookahead_shift; cannot run the reference")
            ref_dates, ref_closes = read_pinned_closes()
            if len(ref_closes) != len(art_closes):
                raise ValueError(f"artifact has {len(art_closes)} price rows, "
                                 f"pinned fixture has {len(ref_closes)}")
            ref = reference.reference_backtest(ref_dates, ref_closes, ref_shift)
            ref_lag = reference.reference_backtest(ref_dates, ref_closes, ref_shift + 1)
        except (OSError, ValueError, ZeroDivisionError) as exc:
            fail("G2_final_equity_oracle", f"reference run failed: {exc}")
            fail("G5_lookahead_control", f"reference run failed: {exc}")

        if ref is not None and metrics is not None and gates.get("G6_schema_sanity", {}).get("pass"):
            try:
                art_eq = metrics["final_equity"]
                rel = abs(art_eq - ref["final_equity"]) / abs(ref["final_equity"])
                gates["G2_final_equity_oracle"] = {"pass": rel <= FINAL_EQUITY_REL_TOL, "detail": (
                    f"artifact final_equity {art_eq:.10f} vs reference "
                    f"{ref['final_equity']:.10f} at lookahead_shift {ref_shift} "
                    f"(relative deviation {rel:.3e}, limit {FINAL_EQUITY_REL_TOL:.0e})")}
                # Supporting numbers surfaced in the verdict's metrics block.
                ref_info = {
                    "final_equity": ref["final_equity"],
                    "total_return": ref["total_return"],
                    "max_drawdown": ref["max_drawdown"],
                    "sharpe": ref["sharpe"],
                    "n_trades": ref["n_trades"],
                    "n_days": ref["n_days"],
                    "lookahead_shift": ref_shift,
                }
            except (ZeroDivisionError, ValueError) as exc:
                fail("G2_final_equity_oracle", str(exc))

            # ---- G3 sharpe self-consistency ------------------------------
            try:
                art_sharpe = metrics["sharpe"]
                csv_sharpe = sharpe_from_returns(rets)
                d = abs(art_sharpe - csv_sharpe)
                gates["G3_sharpe_consistency"] = {"pass": d < SHARPE_ABS_TOL, "detail": (
                    f"metrics.json sharpe {art_sharpe:.10f} vs sharpe recomputed "
                    f"from returns.csv {csv_sharpe:.10f} "
                    f"(mean/std*sqrt(252)); |diff| {d:.3e}, limit {SHARPE_ABS_TOL:.0e}")}
            except (ValueError, ZeroDivisionError, TypeError) as exc:
                fail("G3_sharpe_consistency", str(exc))

            # ---- G4 max drawdown from the artifact's own returns ----------
            try:
                art_mdd = metrics["max_drawdown"]
                csv_mdd = max_drawdown_from_returns(rets)
                d = abs(art_mdd - csv_mdd)
                gates["G4_max_drawdown"] = {"pass": d <= MDD_ABS_TOL, "detail": (
                    f"metrics.json max_drawdown {art_mdd:.10f} vs recomputed from "
                    f"returns.csv {csv_mdd:.10f}; |diff| {d:.3e}, "
                    f"limit {MDD_ABS_TOL:.0e}")}
            except (ValueError, TypeError) as exc:
                fail("G4_max_drawdown", str(exc))

            # ---- G5 lookahead negative control (must-be-different) --------
            # The judge runs its own reference twice around the lag the
            # artifact declares.  An artifact trading a real signal must
            # produce different equity at shift-1 and shift; an artifact
            # whose equity is insensitive to its declared lag is not
            # trading the signal at all, so it must not pass.
            # The declared lag must also BE a shift the reference can run:
            # a lag the reference never uses (e.g. 0, no lag at all) is
            # what a lookahead-cheating engine would declare.
            try:
                e0 = ref["final_equity"]
                e1 = ref_lag["final_equity"]
                rel = abs(e1 - e0) / abs(e0) if e0 else float("inf")
                differs = e1 != e0 and rel > LOOKAHEAD_REL_TOL
                gates["G5_lookahead_control"] = {"pass": differs, "detail": (
                    f"reference final_equity at shift {ref_shift} = {e0:.10f}, at "
                    f"shift {ref_shift + 1} = {e1:.10f}; the two must differ by more "
                    f"than {LOOKAHEAD_REL_TOL:.0e} relative ({rel:.3e})"
                    + ("" if differs else
                       " -- an artifact that trades the same equity under both "
                       "lags is not reacting to its signal lag"))}
            except (ValueError, ZeroDivisionError) as exc:
                fail("G5_lookahead_control", str(exc))

        # ---- verdict ------------------------------------------------------
        # Only the G* gate dicts take part in the verdict; ref_info below is
        # quoted reference output for the human reading the verdict.
        gate_items = [(k, v) for k, v in gates.items() if k.startswith("G")]
        passed = len(gate_items) == 6 and all(v["pass"] for _, v in gate_items)
        failed = [k for k, v in gate_items if not v["pass"]]
        detail_metrics = {}
        if metrics is not None:
            detail_metrics.update({k: metrics[k] for k in REQUIRED_METRIC_KEYS})
        if ref_info is not None:
            detail_metrics["reference"] = ref_info
        verdict = {
            "verdict": "PASS" if passed else "FAIL",
            "artifact": str(artifact),
            "seed": seed,
            "timing": {"wall_s": round(time.monotonic() - t0, 3)},
            "gates": dict(gate_items),
            "failed_gates": failed,
            "metrics": detail_metrics,
        }
        return verdict
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("artifact", help="artifact directory (or its parent)")
    ap.add_argument("--seed", type=int, default=20261014,
                    help="seed recorded in the verdict (the fixture is "
                         "deterministic and pinned; default 20261014)")
    ap.add_argument("--json", metavar="OUT", help="also write the verdict to OUT")
    args = ap.parse_args(argv)

    verdict = grade(Path(args.artifact), args.seed)
    blob = json.dumps(verdict, indent=2)
    print(blob)
    if args.json:
        Path(args.json).write_text(blob + "\n", encoding="utf-8")
    return 0 if verdict["verdict"] == "PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
