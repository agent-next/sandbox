#!/usr/bin/env python3
"""
Generate known-bad mutant artifacts for self-testing the judge.
Each mutant is a single-edit copy of examples/good and must fail at least
one gate (SPEC.md, "Self-test").  Output goes to examples/bad/
(gitignored, regenerated by judge/selftest.sh).
"""

import json
import os
import shutil
import sys

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GOOD = os.path.join(BASE, 'examples', 'good')
BAD = os.path.join(BASE, 'examples', 'bad')


def clone(dst):
    if os.path.exists(dst):
        shutil.rmtree(dst)
    shutil.copytree(GOOD, dst)
    return dst


def read(p):
    with open(p) as f:
        return f.read()


def write(p, s):
    with open(p, 'w') as f:
        f.write(s)


def edit(path, old, new, what):
    s = read(path)
    if old not in s:
        raise RuntimeError('%s: pattern not found for %s' % (path, what))
    write(path, s.replace(old, new, 1))


def main():
    os.makedirs(BAD, exist_ok=True)

    # 1. velocity_flip: the probe splat's velocity is negated in drive.js —
    #    the dye moves opposite its declared direction (gate 3).
    d = clone(os.path.join(BAD, 'velocity_flip'))
    edit(os.path.join(d, 'drive.js'),
         'T.splat(s.probe.x, s.probe.y, s.probe.dx, s.probe.dy, s.probe.rgb)',
         'T.splat(s.probe.x, s.probe.y, -s.probe.dx, -s.probe.dy, '
         's.probe.rgb)',
         'probe velocity flip')

    # 2. obstacles_ignored: the mask program is never installed — dye and
    #    velocity flow straight through the declared obstacles (gate 4).
    d = clone(os.path.join(BAD, 'obstacles_ignored'))
    edit(os.path.join(d, 'drive.js'),
         '    T.setMaskProgram(T.frag());',
         '    // mutant: obstacle mask never installed',
         'setMaskProgram removal')

    # 3. dissipation_zero: declared DENSITY_DISSIPATION set to 0, outside
    #    the SPEC contract range [0.5, 2.0] (gate 5).
    d = clone(os.path.join(BAD, 'dissipation_zero'))
    p = os.path.join(d, 'config.json')
    cfg = json.loads(read(p))
    cfg['config']['DENSITY_DISSIPATION'] = 0.0
    write(p, json.dumps(cfg, indent=2) + '\n')

    # 4. nan_inject: the aim splat gets a NaN velocity — NaN enters the
    #    velocity field and advects into the dye texture (gate 6).
    d = clone(os.path.join(BAD, 'nan_inject'))
    edit(os.path.join(d, 'drive.js'),
         'T.splat(s.aim.x, s.aim.y, s.aim.dx, s.aim.dy, s.aim.rgb)',
         'T.splat(s.aim.x, s.aim.y, NaN, s.aim.dy, s.aim.rgb)',
         'NaN splat velocity')

    # 5. broken_shader: obstacle.frag no longer compiles — setMaskProgram
    #    throws, every frame() throws, the run aborts (gate 1).
    d = clone(os.path.join(BAD, 'broken_shader'))
    edit(os.path.join(d, 'obstacle.frag'),
         'void main () {',
         'void main ( {',
         'shader syntax error')

    print('Created 5 mutants in %s' % BAD)


if __name__ == '__main__':
    sys.exit(main())
