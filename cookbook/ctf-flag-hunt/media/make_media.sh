#!/usr/bin/env bash
# media/make_media.sh — regenerate every media file from real judge output.
#
# Pipeline (nothing is hand-edited or invented):
#   1. make_data.py regrades the committed range, all seven judge mutants
#      and the three agent-loop stages with judge/grade.sh, writing one
#      verdict JSON per run to media/judge_runs/verdicts/
#   2. fig_result.py renders result.png from the good verdict
#   3. fig_loop.py renders loop.png from the loop verdicts + mutants
#   4. video.py renders every frame from the same verdicts, then ffmpeg
#      writes the lossless master (media/master/, gitignored) and the web
#      encode demo.mp4
#   5. write MANIFEST.json (sha256 of each shipped file)
#
# Fails loudly if any expected judge output is missing.

set -euo pipefail

MEDIA_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEMO_DIR="$(dirname "$MEDIA_DIR")"
RUNS="$MEDIA_DIR/judge_runs"
FRAMES="$MEDIA_DIR/master/frames"
MASTER="$MEDIA_DIR/master/demo_master.mp4"
WEB="$MEDIA_DIR/demo.mp4"

PY="${PYTHON:-python3}"
if ! "$PY" -c 'import matplotlib, numpy' >/dev/null 2>&1; then
    echo "make_media: python3 lacks matplotlib/numpy — install them first:" >&2
    exit 1
fi
command -v ffmpeg >/dev/null 2>&1 || { echo "make_media: ffmpeg missing" >&2; exit 1; }
command -v gcc-12 >/dev/null 2>&1 || { echo "make_media: gcc-12 missing (bash judge/setup.sh)" >&2; exit 1; }

"$PY" - <<'PY' || exit 1
import matplotlib, numpy
print(f"[media] matplotlib {matplotlib.__version__}  numpy {numpy.__version__}")
PY
echo "[media] ffmpeg $(ffmpeg -version | head -1 | awk '{print $3}')"

echo "=== 1. real verdict data (grade.sh runs) ==="
mkdir -p "$RUNS"
"$PY" -I "$MEDIA_DIR/make_data.py" "$RUNS"

echo "=== 2. result.png ==="
"$PY" -I "$MEDIA_DIR/fig_result.py" "$RUNS" "$MEDIA_DIR/result.png"

echo "=== 3. loop.png ==="
"$PY" -I "$MEDIA_DIR/fig_loop.py" "$RUNS" "$MEDIA_DIR/loop.png"

echo "=== 4. video (frames + master + web encode) ==="
mkdir -p "$MEDIA_DIR/master"
"$PY" -I "$MEDIA_DIR/video.py" "$RUNS" "$FRAMES" "$MASTER" "$WEB"

echo "=== 5. MANIFEST.json ==="
"$PY" - "$MEDIA_DIR" <<'PY'
import hashlib, json, os, sys

media = sys.argv[1]
entries = []
spec = {
    'result.png': ('Key figure: the C3 token mixer as a function of the '
                   'public inputs (seed, salt, t) with the 300 s acceptance '
                   'window the judge requires -- the value the service '
                   'prints equals the value the judge recomputes in Python '
                   '(oracle check c3).',
                   'bash media/make_media.sh  (fig_result.py)',
                   'media/judge_runs/verdicts/03-good.json'),
    'loop.png': ('The agent loop, replayed with real judge verdicts: the '
                 'broken -> partial -> good stages against the gate counts '
                 'the judge requires, plus the self-test kill matrix for '
                 'all seven mutants.',
                 'bash media/make_media.sh  (fig_loop.py)',
                 'media/judge_runs/verdicts/01-broken.json, '
                 'media/judge_runs/verdicts/02-partial.json, '
                 'media/judge_runs/verdicts/03-good.json, '
                 'media/judge_runs/verdicts/mutant-*.json'),
    'demo.mp4': ('The ctf-flag-hunt video: PASS verdict hook, the five '
                 'services, the token mixer sweeping (2x speed) and the '
                 'mutant kill matrix as a HUD over the real trace, end card '
                 'with the one-command run. Lossless crf 0 master in '
                 'git-ignored media/master/.',
                 'bash media/make_media.sh  (video.py + ffmpeg)',
                 'media/judge_runs/verdicts/*.json'),
}
for fname, (what, cmd, src) in spec.items():
    p = os.path.join(media, fname)
    if not os.path.exists(p):
        raise SystemExit(f'make_media: missing {p}')
    h = hashlib.sha256(open(p, 'rb').read()).hexdigest()
    entries.append({'file': fname, 'what': what, 'command': cmd,
                    'source_data': src, 'sha256': h,
                    'bytes': os.path.getsize(p)})
with open(os.path.join(media, 'MANIFEST.json'), 'w') as f:
    json.dump({'demo': 'cookbook/ctf-flag-hunt',
               'note': 'every number plotted comes from judge verdict JSONs '
                       'regenerated by make_media.sh (seed 20261015)',
               'files': entries}, f, indent=2)
    f.write('\n')
for e in entries:
    print('  %-10s %9d bytes  %s...' % (e['file'], e['bytes'], e['sha256'][:16]))
PY

echo "make_media: done"
