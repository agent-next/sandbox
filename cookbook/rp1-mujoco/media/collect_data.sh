#!/bin/bash
# Collect the real judge outputs the media is built from (DEMO-STANDARD.md:
# every plotted number comes from a file the judge or simulator wrote).
#
#   data/verdicts/<name>.json   grade.sh --json for known-good, the 8
#                               mutants and the replay intermediate
#   data/traces/<name>/trace.csv.gz  grade.sh --trace of the same runs
#                                (gzipped: ~1 MB each raw, and the repo
#                                keeps no file over 1 MB but the media)
#                                (known-good, the video's mutants and the
#                                replay intermediate)
#   data/selftest.txt           the judge self-test's own output
#   work/mutants/               mutants regenerated by judge/mutants.py
#   work/scene/                 the judged scene (pinned model copy with
#                               the 24-dof include), for the 3D renders
#
# Grading order is the replay order of a fixing agent:
#   zero_gains -> no_balance -> weak_balance -> good   (bad -> partly
#   fixed -> good), then the remaining mutants of the kill set.
#
# Requires judge/setup.sh to have run (pinned mujoco venv + model clone).
set -euo pipefail
MEDIA="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEMO="$(dirname "$MEDIA")"
PREFIX="${HOME}/.rp1-mujoco-tools"
MODEL_DIR="${PREFIX}/rp1_description"

[ -x "${PREFIX}/venv/bin/python" ] || { echo "collect: pinned venv missing -- run judge/setup.sh first" >&2; exit 1; }
[ -f "${MODEL_DIR}/mjcf/robot_24dof.xml" ] || { echo "collect: pinned model clone missing -- run judge/setup.sh first" >&2; exit 1; }

mkdir -p "$MEDIA/data/verdicts" "$MEDIA/data/traces" "$MEDIA/work/mutants" "$MEDIA/work/scene"

# --- the judged scene (same assembly grade.sh performs in its scratch) ----
# wiped first: the media work dir is regenerated, never reused across runs
rm -rf "$MEDIA/work/scene/mjcf" "$MEDIA/work/scene/meshes"
cp -r "${MODEL_DIR}/mjcf" "$MEDIA/work/scene/mjcf"
cp -r "${MODEL_DIR}/meshes" "$MEDIA/work/scene/meshes"
sed -i 's|<include file="robot.xml"/>|<include file="robot_24dof.xml"/>|' \
    "$MEDIA/work/scene/mjcf/rp1_flat.xml"
grep -q 'robot_24dof.xml' "$MEDIA/work/scene/mjcf/rp1_flat.xml" \
    || { echo "collect: scene rewrite failed" >&2; exit 1; }

# --- the known-bad family (single edits of examples/good) ------------------
python3 "$DEMO/judge/mutants.py" "$DEMO/examples/good/controller.py" \
    "$MEDIA/work/mutants" >/dev/null

grade() {  # grade <label> <controller.py> [trace]
    local name="$1" ctrl="$2" trace="${3:-}"
    echo "== grade $name =="
    if bash "$DEMO/judge/grade.sh" "$ctrl" \
            --seed 20261014 \
            --json "$MEDIA/data/verdicts/$name.json" \
            ${trace:+--trace "$MEDIA/data/traces/$name"} \
            >/dev/null 2>&1; then
        echo "$name: PASS"
    else
        [ -f "$MEDIA/data/verdicts/$name.json" ] || { echo "$name: no verdict written" >&2; exit 1; }
        echo "$name: FAIL (expected for a mutant)"
    fi
}

# --- the replayed agent loop: bad -> partly fixed -> good ------------------
grade zero_gains "$MEDIA/work/mutants/controller_zero_gains.py"
grade no_balance "$MEDIA/work/mutants/controller_no_balance.py" trace
grade weak_balance "$MEDIA/artifacts/weak_balance.py" trace
grade good "$DEMO/examples/good/controller.py" trace

# --- the rest of the kill set ----------------------------------------------
grade zero_torque  "$MEDIA/work/mutants/controller_zero_torque.py" trace
grade gains_100x   "$MEDIA/work/mutants/controller_gains_100x.py" trace
grade sign_flip_knee   "$MEDIA/work/mutants/controller_sign_flip_knee.py"
grade wrong_joint_order "$MEDIA/work/mutants/controller_wrong_joint_order.py"
grade clamp_1pct   "$MEDIA/work/mutants/controller_clamp_1pct.py"
grade cancels_push "$MEDIA/work/mutants/controller_cancels_push.py"

# --- gzip the traces ---------------------------------------------------------
# grade.sh writes trace.csv (~1 MB per 10 s run); the repo keeps no file
# over 1 MB except the demo media, so the traces are stored gzipped
# (lossless -- the readers in rp1render.py / make_video.py open .gz).
for t in "$MEDIA"/data/traces/*/trace.csv; do
    [ -f "$t" ] && gzip -9 -f "$t"
done

# --- self-test ---------------------------------------------------------------
echo "== selftest =="
bash "$DEMO/judge/selftest.sh" | tee "$MEDIA/data/selftest.txt"

echo "collect: done -> $MEDIA/data"
