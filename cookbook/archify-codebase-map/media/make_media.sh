#!/usr/bin/env bash
# media/make_media.sh — regenerate every media file from real output.
#
# Pipeline (nothing hand-edited or synthesized):
#   1. render the good example's diagram.html with the pinned archify CLI
#      (identically to judge/selftest.sh; the file is git-ignored)
#   2. screenshot it in headless Chromium  -> result.png (1600x1200)
#   3. crop the densest node cluster       -> zoomed.png (900x700,
#      pure-python cut via crop_png.py, no interpolation)
#   4. write MANIFEST.json (sha256 + bytes of each shipped file)
#
# Requires judge/setup.sh to have run (archify skill, chromium, the
# pinned node binary marker, the httpx ground-truth checkout).

set -euo pipefail

MEDIA_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DEMO_DIR="$(dirname "$MEDIA_DIR")"
GOOD_DIR="$DEMO_DIR/examples/good/httpx-map"
TRUTH_ROOT="$HOME/ground-truth/httpx-0.28.1"
ARCHIFY_CLI="$HOME/archify-skill/archify/bin/archify.mjs"
NODE_BIN="$(cat "$HOME/.archify_demo_node" 2>/dev/null || echo node)"

for f in "$ARCHIFY_CLI" "$GOOD_DIR/diagram.json"; do
    [[ -f "$f" ]] || { echo "make_media: missing $f — run judge/setup.sh first" >&2; exit 1; }
done
command -v chromium >/dev/null 2>&1 || { echo "make_media: chromium missing" >&2; exit 1; }
[[ -d "$TRUTH_ROOT/httpx" ]] || { echo "make_media: httpx truth tree missing" >&2; exit 1; }

echo "=== 1. render diagram.html (archify render, as the judge does) ==="
"$NODE_BIN" "$ARCHIFY_CLI" render architecture \
    "$GOOD_DIR/diagram.json" "$GOOD_DIR/diagram.html" \
    --repo-root "$TRUTH_ROOT" >/dev/null
[[ -s "$GOOD_DIR/diagram.html" ]] || { echo "make_media: render produced no file" >&2; exit 1; }

echo "=== 2. result.png (headless Chromium screenshot, 1600x1200) ==="
chromium --headless --disable-gpu --no-sandbox --hide-scrollbars \
    --window-size=1600,1200 --virtual-time-budget=10000 \
    --screenshot="$MEDIA_DIR/result.png" \
    "file://$GOOD_DIR/diagram.html" 2>/dev/null
[[ -s "$MEDIA_DIR/result.png" ]] || { echo "make_media: no screenshot" >&2; exit 1; }

echo "=== 3. zoomed.png (pure-python crop of the _client/_config/_models cluster) ==="
# Fixed window: densest 900x700 region of the 1600x1200 overview,
# measured by non-background pixel count (see RECEIPT.md); x clamped to
# the right edge (704 -> 700) so the window stays inside the frame.
python3 -I "$MEDIA_DIR/crop_png.py" \
    "$MEDIA_DIR/result.png" "$MEDIA_DIR/zoomed.png" 700 176 900 700

echo "=== 4. MANIFEST.json ==="
python3 - "$MEDIA_DIR" <<'PY'
import hashlib, json, os, sys

media = sys.argv[1]
spec = {
    "result.png": (
        "Overview screenshot of the rendered archify diagram of httpx "
        "0.28.1 top-level modules (1600x1200, headless Chromium).",
        "bash media/make_media.sh  (chromium --headless --screenshot of "
        "examples/good/httpx-map/diagram.html)",
        "examples/good/httpx-map/diagram.html (regenerated by archify "
        "render from diagram.json)"),
    "zoomed.png": (
        "Zoomed crop (900x700) of result.png showing the "
        "_client/_config/_models cluster and import edges.",
        "bash media/make_media.sh  (media/crop_png.py: pure-python PNG "
        "cut, no interpolation)",
        "media/result.png"),
}
entries = []
for fname, (what, cmd, src) in spec.items():
    p = os.path.join(media, fname)
    h = hashlib.sha256(open(p, "rb").read()).hexdigest()
    entries.append({"name": fname, "what": what, "command": cmd,
                    "source": src, "sha256": h,
                    "bytes": os.path.getsize(p)})
with open(os.path.join(media, "MANIFEST.json"), "w") as f:
    json.dump({"demo": "cookbook/archify-codebase-map",
               "note": "every frame comes from a real archify render + "
                       "chromium screenshot done by make_media.sh",
               "files": entries}, f, indent=2)
    f.write("\n")
for e in entries:
    print("  %-10s %9d bytes  %s..." % (e["name"], e["bytes"], e["sha256"][:16]))
PY

echo "make_media: done"
